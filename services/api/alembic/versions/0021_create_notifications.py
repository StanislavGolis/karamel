"""create notifications and backfill attendance marker (story 7.3)

Revision ID: 0021
Revises: 0020
Create Date: 2026-10-24

Стори 7.3 (AC-01, AC-02, AC-03; FR107, NFR22, NFR60; ADR-15).

**`notifications` — минимальная таблица-аутбокс, не центр уведомлений**
(решение 1 пакета). Полный центр с UI, настройками и группировкой — эпик 9.
Без этой таблицы 7.3 невыполнима: адресный запрос «подтвердите явку» нельзя
доставить в канал чата, которого у участника может не быть (AC-04 стори).

**Почему `id > 0` рядом с `Identity()`** (D-TD-2, P-10). `Identity()` — это
`GENERATED BY DEFAULT`, то есть явная вставка `id = 0` физически проходит.
В 6.7 на предположении «ноль невозможен» построен класс дефекта; здесь
единственная защита — `CHECK`, поэтому он не декоративен.

**Почему `type` проверяется регексом, а не `Enum`.** Перечень типов растёт
от стори к стори, а NFR60 требует от клиента ИГНОРИРОВАТЬ неизвестный тип.
`Enum` в схеме потребовал бы миграции на каждый новый тип уведомления,
а регекс проверяет форму (`сущность.действие`), не перечень.

**Почему нет `updated_at`** (X-7.1-1). Путь записи — сырой
`INSERT ... SELECT` из воркера: `onupdate` ORM на нём не срабатывает
никогда, и колонка была бы мёртвой, то есть ложным аудитом.

**Почему нет `UNIQUE`** (X-7.3-2). Идемпотентность запроса держится на CAS
карточки (`event_cards.attendance_prompted_at`, ADR-15): ровно один запрос
обеспечивает транзакция карточки, а не ограничение строки уведомления.

**Backfill `attendance_prompted_at` (D-TD-1) — часть этой миграции, и это
БЛОКЕР релиза, а не украшение.** Предикат воркера `starts_at <= now AND
attendance_prompted_at IS NULL AND status IN (...)` НЕ имеет нижней границы
намеренно (D-7.3-4: отсечка по времени превращает лежачего воркера в
необратимый пропуск факта явки, нарушая AC-06 «пропусков 0»). Следствие:
первый прогон после деплоя разослал бы запросы по ВСЕЙ исторической базе —
все карточки `full`/`closed`/`finished`, созданные до 7.3, имеют
`NULL`-маркер (колонка существует с 4.1 и никем не заполнялась).

Backfill выполняется ОДИН раз здесь и помечает карточки, начавшиеся раньше
чем за сутки до релиза: по ним запрос «подтвердите явку» бессмысленен
(встреча давно прошла), а факт встречи по ним уже не восстановить запросом.
Порог «1 сутки» — параметр решения, а не константа поведения: он живёт
только в этой миграции и не порождает второго предиката в коде (P-8).

**`downgrade` с guard.** Непустая `notifications` останавливает откат с
внятным сообщением: адресные запросы — это данные, которые нельзя
уничтожать молча (AC-02, §12.3). Пустая таблица удаляется целиком вместе с
индексом и ограничениями — остатков нет.

**Порядок в `downgrade` обратный:** сначала backfill откатывать не нужно
(маркер карточки — данные, а не схема; откат схемы не должен обнулять
`attendance_prompted_at`, иначе повторный `upgrade` разошлёт запросы), затем
индекс, затем таблица.
"""

import logging
from collections.abc import Sequence

import sqlalchemy as sa

from alembic import op

revision: str = "0021"
_down_revision = "0020"
down_revision: str | Sequence[str] | None = _down_revision
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


#: Имена БЕЗ префикса конвенции: `naming_convention` из `models/base.py`
#: добавит `ck_notifications_`. Литерал с префиксом дал бы двойной префикс —
#: класс дефекта 3.1/4.1, ловится тестом имён ограничений.
ID_POSITIVE_CHECK_NAME = "id_positive"
TYPE_FORMAT_CHECK_NAME = "type_format"
PAYLOAD_OBJECT_CHECK_NAME = "payload_object"
DELIVERY_ORDER_CHECK_NAME = "delivery_order"
READ_ORDER_CHECK_NAME = "read_order"

#: AC-01, NFR60: форма `type` — `сущность.действие`. Дублируется из
#: `app/schemas/ws.py::TYPE_PATTERN` осознанно: миграция обязана читать только
#: `sa` и не импортировать приложение. Расхождение ловится тестом схемы.
TYPE_PATTERN = r"^[a-z_]+\.[a-z_]+$"

#: D-TD-1: граница backfill — параметр решения, не константа кода.
BACKFILL_INTERVAL = "1 day"

#: D-TD-1: статусы, для которых воркер вообще запрашивает подтверждение.
#: Дублируется из `ATTENDANCE_PROMPTABLE_STATUSES` осознанно (та же причина:
#: миграция не импортирует приложение). Совпадение с индексом
#: `ix_event_cards_prompt_due` проверяется тестом S37.
_PROMPTABLE_STATUSES = ("full", "closed", "finished")


def _backfill_attendance_prompted_at() -> None:
    """D-TD-1: помечает исторические карточки, чтобы не разослать запросы по ним.

    Выполняется ТОЛЬКО при живом соединении: в offline-режиме
    (`alembic upgrade --sql`) у контекста нет соединения, и `op.get_bind()`
    вернул бы `None`. Поведение скопировано с `0020` (`_assert_users_ids_positive`):
    offline-режим печатает предупреждение, и оператор обязан выполнить
    `UPDATE` сам — это лучше, чем `AttributeError` на генерации SQL.
    """
    context = op.get_context()
    if context.as_sql:
        # CR 7.3 LOW: предупреждение уходит в ЛОГГЕР, а не в `print`. При
        # `alembic upgrade --sql` stdout — это и есть генерируемый SQL-скрипт,
        # поэтому напечатанная строка попадала в него как невалидная
        # инструкция (`0020` делал именно так — скопированный дефект).
        logging.getLogger("alembic.runtime.migration").warning(
            "offline-режим: backfill `attendance_prompted_at` НЕ выполнен. "
            "Перед применением скрипта выполните вручную: UPDATE event_cards "
            f"SET attendance_prompted_at = now() WHERE attendance_prompted_at IS NULL "
            f"AND starts_at < now() - interval '{BACKFILL_INTERVAL}' "
            f"AND status IN ({', '.join(repr(v) for v in _PROMPTABLE_STATUSES)});"
        )
        return

    statuses = ", ".join(f"'{v}'" for v in _PROMPTABLE_STATUSES)
    op.get_bind().execute(
        sa.text(
            "UPDATE event_cards "
            "   SET attendance_prompted_at = now() "
            " WHERE attendance_prompted_at IS NULL "
            f"   AND starts_at < now() - interval '{BACKFILL_INTERVAL}' "
            f"   AND status IN ({statuses})"
        )
    )


def upgrade() -> None:
    """`notifications` + индекс + backfill маркера карточек (D-TD-1)."""
    op.create_table(
        "notifications",
        sa.Column("id", sa.BigInteger(), sa.Identity(), primary_key=True),
        sa.Column("user_id", sa.BigInteger(), nullable=False),
        sa.Column("type", sa.String(length=64), nullable=False),
        sa.Column("payload", sa.dialects.postgresql.JSONB(), nullable=False),
        sa.Column(
            "created_at",
            sa.DateTime(timezone=True),
            nullable=False,
            server_default=sa.text("now()"),
        ),
        sa.Column("delivered_at", sa.DateTime(timezone=True), nullable=True),
        sa.Column("read_at", sa.DateTime(timezone=True), nullable=True),
        # AC-01: адресат. `CASCADE` — удаление пользователя уносит его уведомления.
        sa.ForeignKeyConstraint(
            ["user_id"],
            ["users.id"],
            name=op.f("fk_notifications_user_id_users"),
            ondelete="CASCADE",
        ),
        # AC-01, D-TD-2: единственная защита от явной вставки неположительного id.
        sa.CheckConstraint("id > 0", name=ID_POSITIVE_CHECK_NAME),
        # AC-01, NFR60: форма типа, не перечень.
        sa.CheckConstraint(f"type ~ '{TYPE_PATTERN}'", name=TYPE_FORMAT_CHECK_NAME),
        # AC-01, NFR60: payload — объект. `jsonb_typeof` на массиве даёт
        # 'array', на скаляре — 'string'/'number': сравнение с 'object' ложно
        # в обоих случаях (в отличие от `?`-операторов, дающих NULL).
        sa.CheckConstraint("jsonb_typeof(payload) = 'object'", name=PAYLOAD_OBJECT_CHECK_NAME),
        # AC-01: доставка не раньше создания, прочтение не раньше доставки.
        sa.CheckConstraint("delivered_at >= created_at", name=DELIVERY_ORDER_CHECK_NAME),
        sa.CheckConstraint("read_at >= delivered_at", name=READ_ORDER_CHECK_NAME),
    )

    # AC-01: будущий список «мои уведомления» эпика 9 — предикат
    # `user_id = :u` с сортировкой/фильтром по `delivered_at`.
    op.create_index("ix_notifications_user_delivery", "notifications", ["user_id", "delivered_at"])

    _backfill_attendance_prompted_at()


def downgrade() -> None:
    """Откат с guard: непустая `notifications` останавливает удаление (AC-02).

    Guard обязателен: адресные запросы — данные, а `DROP TABLE` уничтожил бы
    их молча. Оператор решает судьбу строк осознанно (§12.3), а не узнаёт о
    потере из логов.

    `attendance_prompted_at` НЕ обнуляется: это данные карточек, а не схема.
    Обнуление при откате означало бы, что повторный `upgrade` разошлёт запросы
    по всей истории — ровно то, что закрывает D-TD-1.
    """
    context = op.get_context()
    # CR 7.3 LOW: guard НЕ обходится в offline-режиме. Прежде при
    # `downgrade --sql` генерировался `DROP TABLE` без единой проверки —
    # защита отсутствовала ровно там, где скрипт отдают оператору.
    # Соединения нет, поэтому проверить данные нельзя — и тогда это явный
    # отказ с инструкцией, а не молчаливое уничтожение.
    if context.as_sql:
        raise RuntimeError(
            "Откат 0021 в offline-режиме (`--sql`) запрещён: проверить наличие "
            "строк в notifications невозможно, а `DROP TABLE` уничтожил бы "
            "адресные запросы молча. Выполните откат онлайн (без `--sql`) — "
            "guard проверит count(*) и остановится при непустой таблице."
        )
    rows = op.get_bind().execute(sa.text("SELECT count(*) FROM notifications")).scalar_one()
    if rows:
        raise RuntimeError(
            f"Откат 0021 невозможен: в notifications {rows} строк. DROP TABLE "
            "уничтожил бы адресные запросы молча, а они — входные данные "
            "доставки (эпик 9) и истории явок (7.5). Выгрузите или удалите "
            "строки осознанно, затем повторите откат."
        )

    op.drop_index("ix_notifications_user_delivery", table_name="notifications")
    op.drop_table("notifications")
