"""access_logs table for moderator access auditing (story 8.6, AC-01, AC-06)

Revision ID: 0029
Revises: 0028
Create Date: 2026-10-25

**Зачем таблица.** NFR32 требует «**холодное хранилище**; содержат: кто,
когда, к какому диалогу / карточке». `structlog` из 8.3 пишет в stdout
процесса и уходит в ротацию контейнера — из него нельзя ответить «кто
открывал переписку этого человека за полгода», а NFR42 требует шесть
месяцев. Отдельная таблица позволяет вынести её в холодное хранилище
физически, не меняя кода записи.

**Почему НИ ОДНОГО FK** (D-92). `ON DELETE SET NULL` обнулял бы `chat_uuid`
при удалении чата (каскад от карточки, 8.2), и запись перестала бы отвечать
на вопрос «к какому диалогу был доступ» — ровно то, ради чего NFR32 требует
хранилище. Append-only лог фиксирует факт о ПРОШЛОМ и не должен зависеть от
жизненного цикла того, что фиксирует. UUID — публичные стабильные адреса
(D-2), их достаточно для расследования.

**Почему нет колонки для текста** (D-91). Утечка невыразима на уровне схемы:
нельзя «забыть отфильтровать» поле, которого нет. Ни `body`, ни `reason`,
ни `message` — только идентификаторы и `message_count` (NFR27).

**Почему индексы `CONCURRENTLY`** (D-4). Таблица создаётся пустой, но
`CREATE INDEX` на ней сразу после `CREATE TABLE` в той же транзакции всё
равно берёт `ACCESS EXCLUSIVE` на таблицу — а следующий деплой может
столкнуться с уже заполненной таблицей. Одинаковый приём на всех миграциях
эпика: путь проверен, поведение предсказуемо.

**Почему `downgrade` БЕЗ `CONCURRENTLY`** (CR 8.2, H-1). `autocommit_block`
коммитит оператор вне транзакции ревизии: остановка guard'ом ниже оставила
бы индексы снесёнными навсегда при формально верном `alembic_version`.

**Offline-safe** (D-7). В `--sql` режиме `indisvalid` не проверить — обе
функции падают явно, а не генерируют скрипт без guard'а.
"""

from collections.abc import Sequence

import sqlalchemy as sa

from alembic import op

revision: str = "0029"

down_revision: str | None = "0028"

branch_labels: str | Sequence[str] | None = None

depends_on: str | Sequence[str] | None = None

#: AC-06, NFR42: ретенция 6 месяцев. Индекс нужен уже сейчас: без него
#: будущий `DELETE ... WHERE created_at < now() - interval '6 months'`
#: (эпик 10) сделает seq scan по растущей таблице.
CREATED_INDEX = "ix_access_logs_created_at"

#: Разбор инцидента: «что открывал этот модератор». Составной с `DESC` —
#: без второго столбца планировщик добавил бы `Sort` на каждый запрос.
MODERATOR_INDEX = "ix_access_logs_moderator_uuid_created_at"

#: AC-01, AC-08: домен действий. `CHECK` вместо нативного enum (D-3 стиля
#: проекта): набор значений меняется одной миграцией, без `ALTER TYPE`.
ACCESS_ACTIONS: tuple[str, ...] = ("fragment_read", "card_read")


def _assert_offline_safe(action: str) -> None:
    """D-7: в `--sql`-режиме guard непроверяем — падаем явно."""
    if op.get_context().as_sql:
        raise RuntimeError(
            f"`{action} --sql` для 0029 запрещён: `CREATE INDEX CONCURRENTLY` "
            "не выражается в offline-скрипте, а guard по `indisvalid` требует "
            "соединения с БД. Выполните онлайн."
        )


def _assert_index_valid(name: str) -> None:
    """D-18: прерванное `CONCURRENTLY`-построение оставляет невалидный индекс.

    CR 8.3, H-3: `to_regclass`, а НЕ `'name'::regclass` — приведение на
    несуществующем имени БРОСАЕТ `UndefinedTableError`, и ветка «индекс не
    создан» ушла бы мимо guard'а сырой ошибкой драйвера.
    """
    valid = (
        op.get_bind()
        .execute(
            sa.text("SELECT indisvalid FROM pg_index WHERE indexrelid = to_regclass(:name)"),
            {"name": name},
        )
        .scalar_one_or_none()
    )
    if valid is not True:
        raise RuntimeError(
            f"Индекс {name} не построен или невалиден (indisvalid={valid!r}). "
            "Пересоздайте индекс вручную и повторите `upgrade`."
        )


def upgrade() -> None:
    """AC-01, AC-08: таблица аудита → два индекса (AC-06)."""
    _assert_offline_safe("upgrade")

    op.create_table(
        "access_logs",
        # P-10: `Identity()` = `GENERATED BY DEFAULT`, явная вставка id=0
        # физически проходит — `CHECK (id > 0)` не декоративен.
        sa.Column("id", sa.BigInteger(), sa.Identity(), primary_key=True),
        sa.Column(
            "uuid",
            sa.dialects.postgresql.UUID(as_uuid=True),
            nullable=False,
            server_default=sa.text("gen_random_uuid()"),
        ),
        # D-92: `moderator_uuid` NOT NULL — у факта доступа всегда есть автор
        # (модератор удалён — остаётся UUID; аккаунт пересоздан — тот же
        # адрес не вернётся, но факт остаётся атрибутируемым по значению).
        sa.Column("moderator_uuid", sa.dialects.postgresql.UUID(as_uuid=True), nullable=False),
        # AC-01, AC-08: что именно открывали.
        sa.Column("action", sa.String(24), nullable=False),
        # AC-01: цель доступа. Все четыре — NULL-able: у `card_read` нет
        # диалога, у `fragment_read` нет `subject_uuid`.
        sa.Column("subject_uuid", sa.dialects.postgresql.UUID(as_uuid=True), nullable=True),
        sa.Column("report_uuid", sa.dialects.postgresql.UUID(as_uuid=True), nullable=True),
        sa.Column("chat_uuid", sa.dialects.postgresql.UUID(as_uuid=True), nullable=True),
        sa.Column("card_uuid", sa.dialects.postgresql.UUID(as_uuid=True), nullable=True),
        # AC-03: сколько отдано. `SMALLINT`: FR40 ограничивает фрагмент десятью,
        # но запас до 32767 стоит два байта и снимает вопрос при смене лимита.
        sa.Column("message_count", sa.SmallInteger(), nullable=True),
        # NFR42: момент доступа. По нему считается ретенция (эпик 10).
        sa.Column(
            "created_at",
            sa.DateTime(timezone=True),
            nullable=False,
            server_default=sa.func.now(),
        ),
        # AC-01, NFR32: исходный путь запроса — для разбора «как именно
        # открыли». Строка, а не enum: маршрут меняется чаще домена действий.
        sa.Column("route", sa.String(128), nullable=True),
        sa.PrimaryKeyConstraint("id"),
        sa.UniqueConstraint("uuid", name="uq_access_logs_uuid"),
        sa.CheckConstraint("id > 0", name="id_positive"),
        sa.CheckConstraint(
            "action IN (" + ", ".join(f"'{value}'" for value in ACCESS_ACTIONS) + ")",
            name="action_allowed",
        ),
        # D-91: «текста нет по построению» — защищено ОТСУТСТВИЕМ колонки.
        # Комментарий здесь стоит как предупреждение будущему: добавление
        # `body`/`reason` нарушит AC-02 и NFR27.
    )

    for name, columns in (
        (CREATED_INDEX, "(created_at)"),
        (MODERATOR_INDEX, "(moderator_uuid, created_at DESC)"),
    ):
        with op.get_context().autocommit_block():
            op.execute(f"CREATE INDEX CONCURRENTLY IF NOT EXISTS {name} ON access_logs {columns}")
        _assert_index_valid(name)


def downgrade() -> None:
    """Снимает индексы АТОМАРНО, затем таблицу (CR 8.2, H-1)."""
    _assert_offline_safe("downgrade")

    # Без `CONCURRENTLY` и без `autocommit_block`: откат обязан быть атомарным.
    op.execute(f"DROP INDEX IF EXISTS {CREATED_INDEX}")
    op.execute(f"DROP INDEX IF EXISTS {MODERATOR_INDEX}")

    op.drop_table("access_logs")
