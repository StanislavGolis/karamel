def _assert_users_ids_positive() -> None:
    """AC-06: предусловие перед `CHECK (id > 0)` на `users`.

    CR 7.1 (§patch): в offline-режиме (`alembic upgrade --sql`) у контекста
    нет соединения, и `op.get_bind()` возвращает `None` — обращение к нему
    падало `AttributeError`, ломая генерацию статического SQL для всей
    цепочки (а offline-режим включён в `alembic/env.py`). Поэтому проверка
    выполняется ТОЛЬКО при живом соединении; в offline-режиме печатается
    предупреждение, и DDL генерируется без проверки — оператор обязан
    прогнать её сам (она и создана ради внятного сообщения вместо падения
    `ALTER` поверх мусора).
    """
    context = op.get_context()
    if context.as_sql:
        print(  # noqa: T201 — предупреждение видно в stdout генерации SQL
            "WARNING: offline-режим: предусловие `SELECT count(*) FROM users "
            "WHERE id <= 0` НЕ выполнено. Перед применением скрипта проверьте "
            "отсутствие строк с неположительным id вручную."
        )
        return

    connection = op.get_bind()
    invalid_users = connection.execute(
        sa.text("SELECT count(*) FROM users WHERE id <= 0")
    ).scalar_one()
    if invalid_users:
        raise RuntimeError(
            f"Миграция 0020 невозможна: в users {invalid_users} строк с id <= 0. "
            "CHECK (id > 0) не создаётся поверх мусора — исправьте id вручную "
            "(строки с неположительным id ломают публичную адресацию по uuid)."
        )


