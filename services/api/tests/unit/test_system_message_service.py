"""Системные сообщения компании (стори 6.7; AC-01…AC-04).

§18.2: проверяются наблюдаемые свойства — форма предикатов SQL, набор
шаблонов, детерминированность AAD, — а не факт объявления функций.

§18.11: каждый признак проверяется в ОБОИХ значениях: `is_system` true и
false, `sender_id` NULL и не-NULL, unread до и после прочтения.
"""

from __future__ import annotations

import uuid as uuid_lib
from datetime import UTC, datetime

import pytest
from cryptography.exceptions import InvalidTag

from app.core.crypto import decrypt_message_body, encrypt_message_body
from app.repositories.messages import MessageRepository
from app.services.system_message_service import (
    SYSTEM_MESSAGE_TEMPLATES,
    SystemMessageKind,
)

CHAT_ID = 7
VIEWER_ID = 13
KEY = "k" * 40
CHAT_UUID = uuid_lib.UUID("77777777-7777-4777-8777-777777777777")
MESSAGE_UUID = uuid_lib.UUID("88888888-8888-4888-8888-888888888888")


def _sql(statement: object) -> str:
    """Текст запроса с подставленными параметрами (приём 4.1)."""
    return str(
        statement.compile(  # type: ignore[attr-defined]
            compile_kwargs={"literal_binds": True}
        )
    )


# ——— D-6.7-3: AAD системного сообщения ———


def test_system_aad_is_a_domain_not_a_number() -> None:
    """AC-04, CR 6.7 (A-1): системный AAD НЕ совпадает ни с одним `users.id`.

    Прежняя версия утверждала `SYSTEM_AAD_SENDER_ID == 0` и обосновывала
    «`users.id` начинается с 1». Это ЛОЖНО на уровне схемы: `users.id`
    объявлен `Identity()`, а PostgreSQL создаёт `GENERATED BY DEFAULT`,
    который РАЗРЕШАЕТ явную вставку `id = 0`. Если такой пользователь
    появится, AAD системного сообщения совпадёт с AAD его сообщения, и
    блоб можно будет выдать за чужое сообщение.

    Краснеет, если маркером системности снова сделают число: `_aad` с
    `sender_id=None` обязан отличаться от `_aad` с любым `int`, включая 0.
    """
    from app.core import crypto

    system_aad = crypto._aad(chat_id=CHAT_ID, sender_id=None)
    for numeric_id in (0, 1, 2, 10**9):
        assert system_aad != crypto._aad(chat_id=CHAT_ID, sender_id=numeric_id)
    # Формат обычного сообщения НЕ изменился: старые блобы читаются как есть.
    assert crypto._aad(chat_id=CHAT_ID, sender_id=10) == f"chat:{CHAT_ID}|sender:10".encode()
    # Домен системного сообщения — строка, а не число.
    assert system_aad == f"chat:{CHAT_ID}|sender:system".encode()


def test_system_blob_is_bound_to_the_chat() -> None:
    """AC-04, D-6.7-3: перенос системного блоба в другой чат ломает тег.

    Краснеет, если AAD перестанет содержать `chat_id` (тогда блоб стал бы
    переносимым между чатами — ровно то, что CR 6.1 запретил для обычных).
    """
    blob = encrypt_message_body(
        "Участник отменил участие", chat_id=CHAT_ID, sender_id=None, key=KEY
    )

    assert (
        decrypt_message_body(blob, chat_id=CHAT_ID, sender_id=None, key=KEY)
        == "Участник отменил участие"
    )
    with pytest.raises(InvalidTag):
        decrypt_message_body(blob, chat_id=CHAT_ID + 1, sender_id=None, key=KEY)
    # CR 6.7 (A-1): блоб системного НЕ читается как сообщение пользователя 0.
    with pytest.raises(InvalidTag):
        decrypt_message_body(blob, chat_id=CHAT_ID, sender_id=0, key=KEY)


# ——— D-6.7-5: шаблоны только серверные ———


def test_templates_cover_all_kinds_and_carry_no_identity() -> None:
    """AC-01…AC-04, D-6.7-5: по шаблону на каждый триггер, без ПД и идентификаторов.

    Краснеет от: (а) нового `SystemMessageKind` без шаблона (KeyError в
    проде), (б) подстановки имени/`uuid` в текст (анти-оракул FR81).
    """
    assert set(SYSTEM_MESSAGE_TEMPLATES) == set(SystemMessageKind)

    for text in SYSTEM_MESSAGE_TEMPLATES.values():
        assert text.strip()
        # Никаких подстановок: шаблон — константа, а не `.format`-строка.
        assert "{" not in text and "}" not in text
        # Кириллица + пробелы: латиница означала бы техническую строку.
        assert any("а" <= char.lower() <= "я" for char in text)


def test_templates_are_distinct() -> None:
    """AC-01…AC-03: три разных факта не описываются одним текстом.

    Краснеет, если шаблоны скопируют: участник не отличит «отменил участие»
    от «отменил встречу».
    """
    assert len(set(SYSTEM_MESSAGE_TEMPLATES.values())) == len(SystemMessageKind)


# ——— Task 3: NULL-безопасные предикаты ———


def test_history_statement_outer_joins_sender() -> None:
    """AC-01, Task 3.1: история не теряет системные сообщения.

    Краснеет, если `outerjoin` вернут в `join`: `INNER JOIN users ON id =
    sender_id` выбрасывает строки с `sender_id IS NULL`, и системное
    сообщение ИСЧЕЗАЕТ из чата — молчаливая потеря, а не ошибка.
    """
    sql = _sql(MessageRepository.build_history_statement(chat_id=CHAT_ID, after=None, limit=30))

    assert "outer join users" in sql.lower().replace("left outer join", "outer join")


def test_mark_read_statement_counts_system_messages() -> None:
    """AC-04, D-6.7-2, Task 3.4: `mark_read` закрывает и системные.

    Краснеет, если останется только `sender_id != :viewer`: у системного
    `sender_id IS NULL`, сравнение даёт `NULL`, предикат ложен — и сообщение
    НАВСЕГДА остаётся непрочитанным (счётчик, который нечем обнулить).
    """
    sql = _sql(MessageRepository.build_mark_read_statement(chat_id=CHAT_ID, viewer_id=VIEWER_ID))
    lowered = sql.lower()

    assert "sender_id is null" in lowered
    assert "sender_id !=" in lowered


def test_insert_statement_marks_system_rows() -> None:
    """AC-04, Task 3.5: вставка пишет `is_system` явно.

    Краснеет, если `is_system` не попадёт в `values`: у системной строки
    останется `server_default = false`, и `CHECK`-инвариант не сработает —
    сообщение без автора станет «обычным».
    """
    statement = MessageRepository.build_insert_statement(
        chat_id=CHAT_ID,
        sender_id=None,
        body=b"x" * 40,
        message_uuid=MESSAGE_UUID,
        client_message_id=None,
        is_system=True,
    )
    sql = _sql(statement)

    assert "is_system" in sql.lower()
    # Системная вставка не участвует в `ON CONFLICT`: клиентского id нет.
    assert "on conflict" not in sql.lower()


def test_insert_statement_for_regular_message_keeps_conflict_clause() -> None:
    """AC-04, §18.11: обычная вставка сохраняет идемпотентность NFR18.

    Краснеет, если `ON CONFLICT` уберут ради системных: повтор отправки после
    обрыва создаст дубль.
    """
    client_id = uuid_lib.uuid4()
    statement = MessageRepository.build_insert_statement(
        chat_id=CHAT_ID,
        sender_id=VIEWER_ID,
        body=b"x" * 40,
        message_uuid=MESSAGE_UUID,
        client_message_id=client_id,
        is_system=False,
    )

    assert "on conflict" in _sql(statement).lower()


def test_unread_statement_counts_system_messages() -> None:
    """AC-04, D-6.7-2: системные считаются непрочитанными в списке чатов.

    Краснеет, если предикат останется `sender_id != :viewer`: у системного
    `NULL != :viewer` → `NULL` → строка НЕ считается, и чат с изменившимся
    составом выглядит прочитанным.
    """
    statement = MessageRepository.build_unread_predicate(viewer_id=VIEWER_ID)
    sql = _sql(statement.select() if hasattr(statement, "select") else statement)

    assert "sender_id is null" in sql.lower() or "is_system" in sql.lower()


# ——— порядок ADR-11 ———


def test_publish_payload_for_system_message_is_anonymous() -> None:
    """AC-01…AC-04, D-6.7-4: payload системного события без автора.

    Краснеет, если `sender_uuid` подставят нулевым uuid или `is_system`
    забудут: клиент отрисовал бы системное сообщение как сообщение
    пользователя (со своим аватаром и кнопкой удаления).
    """
    from app.services.system_message_service import build_system_envelope

    created_at = datetime(2026, 10, 24, 12, 0, tzinfo=UTC)
    envelope = build_system_envelope(
        chat_uuid=CHAT_UUID,
        message_uuid=MESSAGE_UUID,
        body="Автор отменил встречу",
        created_at=created_at,
    )

    assert envelope.type == "message.created"
    assert envelope.payload["is_system"] is True
    assert envelope.payload["sender_uuid"] is None
    assert envelope.payload["message_uuid"] == str(MESSAGE_UUID)
    assert envelope.payload["body"] == "Автор отменил встречу"
    assert envelope.payload["created_at"].endswith("Z")
