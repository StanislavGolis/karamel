"""Порог просрочки жалобы: диапазон `1..168` (стори 8.3; CR H-4; NFR52, NFR63).

**Почему этот файл существует.** Стори 8.3 заявляла валидатор в Dev Notes
(«Валидатор: `1..168`»), но в `app/core/config.py` его не было: значение
принималось любым. Заявленное расходилось с фактическим, и молчаливое
расхождение — ровно то, что CR обязан ловить.

**Почему проверяется ПОВЕДЕНИЕ, а не наличие метода.** Тест на `hasattr`
был бы тавтологией (§18.2): зелёный и при валидаторе, который ничего не
отвергает. Здесь конфигурация реально создаётся с граничными значениями.
"""

from __future__ import annotations

import pytest
from pydantic import ValidationError

from app.core.config import Settings


@pytest.mark.parametrize("hours", [1, 20, 168])
def test_valid_range_accepted(hours: int) -> None:
    """Границы `1` и `168` включены; `20` — продуктовое значение по умолчанию.

    Неделя выбрана верхней границей: жалоба, не разобранная за неделю,
    просрочена при любом разумном SLA, а большее значение сделало бы метку
    `overdue` недостижимой и NFR52 невыполнимым молча.
    """
    assert Settings(reports_overdue_hours=hours).reports_overdue_hours == hours


@pytest.mark.parametrize("hours", [0, -1, -168, 169, 100000])
def test_out_of_range_rejected(hours: int) -> None:
    """`0` и отрицательные делают просроченной ЛЮБУЮ жалобу.

    Порог участвует в сравнении `(now - reported_at) > threshold`: при `0`
    жалоба, поданная секунду назад, уже «просрочена», и метка перестаёт
    что-либо значить. При больших значениях она недостижима. Оба случая —
    ошибка конфигурации и должны ронять старт, как соседние лимиты.
    """
    with pytest.raises(ValidationError):
        Settings(reports_overdue_hours=hours)


def test_default_is_twenty_hours() -> None:
    """NFR52: продуктовый дефолт — 20 часов.

    Тест фиксирует ДЕФОЛТ, а не константу в коде: если его поменяют, это
    должно быть осознанным решением с правкой NFR52, а не побочным эффектом.
    """
    assert Settings().reports_overdue_hours == 20
