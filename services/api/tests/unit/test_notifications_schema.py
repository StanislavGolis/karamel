"""Схема `Notification` против миграций `0021` (7.3) и `0030` (9.1; AC-01, AC-02).

**Почему unit, а не integration.** Состав колонок, имена ограничений и
отсутствие `updated_at` — свойства метаданных, а не БД: их видно без
PostgreSQL. Цена ошибки при этом высока (P-13): мутация по модели и мутация
по миграции должны краснеть ОБЕ, иначе однократная проверка даёт ложную
зелень (прецедент 6.1/M1: 0 failed по модели, 16 failed по модели+миграции).

Проверки здесь — про ФОРМУ: колонки, `nullable`, имена `ck_`/`fk_`/`ix_`,
регекс типа, `jsonb`-предикат, `Identity()` + `CHECK (id > 0)`, отсутствие
`updated_at` (X-7.1-1). Поведение БД (реальный `CHECK`, `Cascade`,
`pg_indexes`) — в integration-файлах.
"""

from __future__ import annotations

import re

import pytest
from sqlalchemy import CheckConstraint, Identity, UniqueConstraint

from app.models.notification import Notification
from app.schemas.ws import TYPE_PATTERN


def _checks() -> dict[str, str]:
    return {
        str(constraint.name): str(constraint.sqltext)
        for constraint in Notification.__table__.constraints
        if isinstance(constraint, CheckConstraint)
    }


def test_columns_match_ac01() -> None:
    """AC-01: состав колонок ровно как в миграции, без лишних.

    Краснеет от «добавили удобное поле» и от «забыли `delivered_at`».
    """
    assert set(Notification.__table__.columns.keys()) == {
        "id",
        # AC-01 стори 9.1 (D-9.1-8): публичный ID. В 7.3 его не было намеренно —
        # таблица не адресовалась по API. С 9.1 уведомление адресуется.
        "uuid",
        "user_id",
        "type",
        "payload",
        "created_at",
        "delivered_at",
        "read_at",
    }


def test_no_updated_at() -> None:
    """X-7.1-1: `TimestampMixin` НЕ наследуется — `updated_at` мёртв.

    Путь записи — сырой `INSERT ... SELECT` из воркера: `onupdate` ORM на нём
    не срабатывает никогда. Колонка была бы ложным аудитом «когда менялось».
    """
    assert "updated_at" not in Notification.__table__.columns


def test_created_at_not_nullable_with_server_default() -> None:
    """AC-01: `created_at` явно, с серверным `now()` (вставка вне ORM)."""
    column = Notification.__table__.columns["created_at"]
    assert column.nullable is False
    assert column.server_default is not None


def test_payload_is_jsonb_not_nullable() -> None:
    """AC-01, NFR60: `payload` — `jsonb`, не `json`/`text`."""
    column = Notification.__table__.columns["payload"]
    assert column.type.__class__.__name__ == "JSONB"
    assert column.nullable is False


def test_id_has_identity_and_positive_check() -> None:
    """AC-01, D-TD-2: `Identity()` И `CHECK (id > 0)` — оба, не одно.

    P-10: `Identity()` = `GENERATED BY DEFAULT`, явная вставка `id = 0`
    физически проходит. Без `CHECK` строка с «невозможным» id станет
    реальной (прецедент 6.7, CRITICAL).
    """
    column = Notification.__table__.columns["id"]
    assert isinstance(column.identity, Identity)
    assert _checks()["ck_notifications_id_positive"] == "id > 0"


def test_constraint_names_follow_convention() -> None:
    """AC-01: имена ограничений детерминированы (конвенция из `base.py`).

    Литерал с префиксом дал бы `ck_notifications_ck_notifications_...` —
    класс дефекта 3.1/4.1, который ловится только сравнением имён.
    """
    assert set(_checks()) == {
        "ck_notifications_id_positive",
        # AC-02 стори 9.1 (D-9.1-3): ПЕРЕЧЕНЬ типов поверх проверки формы.
        "ck_notifications_type",
        "ck_notifications_type_format",
        "ck_notifications_payload_object",
        "ck_notifications_delivery_order",
        "ck_notifications_read_order",
    }
    # Имя FK живёт на уровне ограничения, а не колоночного `ForeignKey`:
    # у последнего `name` = None до сборки `Table`.
    foreign_keys = {str(fk.name) for fk in Notification.__table__.foreign_key_constraints}
    assert foreign_keys == {"fk_notifications_user_id_users"}
    indexes = {str(index.name) for index in Notification.__table__.indexes}
    assert indexes == {
        # 7.3: предикат доставки (`delivered_at IS NULL`).
        "ix_notifications_user_delivery",
        # AC-03 стори 9.1: предикат прочтения.
        "ix_notifications_user_read",
    }


def test_read_order_is_biconditional_expression() -> None:
    """CR 7.3 H-2 (M18): `read_order` — бикондиционал, а не `read_at >= delivered_at`.

    Тест имён ограничений ловит только ПЕРЕИМЕНОВАНИЕ. Здесь проверяется
    ТЕКСТ выражения: прежняя форма пропускала `read_at` без `delivered_at`
    (при `delivered_at IS NULL` выражение даёт `UNKNOWN`, а `CHECK` отвергает
    только `FALSE`). Краснеет от отката на слабое выражение.
    """
    checks = {
        str(c.name).removeprefix("ck_notifications_"): str(c.sqltext)
        for c in Notification.__table__.constraints
        if isinstance(c, CheckConstraint)
    }
    expression = checks["read_order"]
    assert "delivered_at IS NULL" in expression
    assert "read_at IS NULL" in expression
    assert "read_at >= delivered_at" in expression


def test_user_id_foreign_key_cascades() -> None:
    """AC-01: `FK user_id → users.id ON DELETE CASCADE`.

    `CASCADE` — не удобство: удаление пользователя обязано уносить его
    адресные запросы (ретенция ADR-07).
    """
    (foreign_key,) = Notification.__table__.foreign_keys
    assert foreign_key.ondelete == "CASCADE"
    assert foreign_key.column.table.name == "users"


def test_unique_constraint_only_on_uuid() -> None:
    """X-7.3-2 + AC-01 стори 9.1: `UNIQUE` — ТОЛЬКО публичный адрес.

    **Почему не «UNIQUE нет вообще» (прежняя форма теста).** В 7.3 ограничений
    не было намеренно: идемпотентность запроса явки держит CAS карточки
    (`event_cards.attendance_prompted_at`, ADR-15), а не строка уведомления.
    Это остаётся верным и в 9.1 — `UNIQUE (user_id, type, payload)` «на всякий
    случай» вернул бы ту же ошибку: он запрещал бы легитимные повторы.

    Но `uuid` — публичный адрес (project-context §7), и он обязан быть
    уникальным. Тест различает два случая: UNIQUE по `uuid` разрешён,
    любой другой — нет.
    """
    unique = [c for c in Notification.__table__.constraints if isinstance(c, UniqueConstraint)]
    columns = {tuple(col.name for col in constraint.columns) for constraint in unique}
    assert columns == {("uuid",)}, f"лишние UNIQUE: {columns}"


@pytest.mark.parametrize("value", ["attendance.request", "message.created", "a.b"])
def test_type_check_accepts_entity_action(value: str) -> None:
    """AC-01, NFR60: форма `сущность.действие` проходит."""
    assert re.match(TYPE_PATTERN, value)


@pytest.mark.parametrize("value", ["AttendanceRequest", "", "a.b.c", "Attendance.Request", "a"])
def test_type_check_rejects_other_forms(value: str) -> None:
    """AC-01: `AttendanceRequest`, пустая строка, `a.b.c` — отвергаются."""
    assert not re.match(TYPE_PATTERN, value)


def test_type_check_sql_uses_same_pattern() -> None:
    """AC-01: модель и `TYPE_PATTERN` не разошлись.

    Третья копия регекса (модель, миграция, схема WS) — это класс дефекта 4.1:
    `attendance.request` обязан проходить во всех трёх местах.
    """
    sql = _checks()["ck_notifications_type_format"]
    assert "~" in sql
    assert TYPE_PATTERN in sql
