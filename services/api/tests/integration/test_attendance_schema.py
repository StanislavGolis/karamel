# --- CR 7.1: исполнение STATUS_CASE_SQL против живой БД -----------------------


#: AC-03, CR 7.1 (HIGH): все 9 комбинаций трёхзначной логики.
#: Отдельная копия от `TRUTH_TABLE`, потому что здесь проверяется ИСПОЛНЕНИЕ
#: SQL, а не форма константы.
_STATUS_COMBINATIONS: list[tuple[bool | None, bool | None]] = [
    (None, None),
    (None, True),
    (None, False),
    (True, None),
    (True, True),
    (True, False),
    (False, None),
    (False, True),
    (False, False),
]


@pytest.mark.parametrize(("author_c", "participant_c"), _STATUS_COMBINATIONS)
async def test_status_case_sql_matches_derive(
    session: AsyncSession, author_c: bool | None, participant_c: bool | None
) -> None:
    """AC-03, CR 7.1: `STATUS_CASE_SQL` ИСПОЛНЯЕТСЯ и даёт статус `derive`.

    До этого теста `STATUS_CASE_SQL` не исполнялся ни одним тестом: unit-тест
    `test_sql_case_and_python_agree_on_all_combinations` сравнивал
    `derive_attendance_status` с `_eval_status_case` — рукописной Python-копией
    ветвей. Доказано мутацией: `THEN 'no_show'` → `THEN 'confirmed'` в реальном
    SQL оставляла 16 unit-тестов зелёными.

    Здесь SQL уходит в PostgreSQL как `SELECT <STATUS_CASE_SQL> FROM (VALUES ...)`
    и ответ БД сравнивается с Python-справочником. Краснеет при любой правке
    любой ветки `CASE` — то есть закрывает ровно тот класс дефекта P-8
    («два представления одного правила разошлись молча»), ради которого
    правило и объявлено существующим в двух видах.
    """
    result = await session.execute(
        text(
            f"SELECT {STATUS_CASE_SQL} "
            "FROM (VALUES (CAST(:a AS boolean), CAST(:p AS boolean))) "
            "AS v(author_confirmed, participant_confirmed)"
        ),
        {"a": author_c, "p": participant_c},
    )
    sql_status = result.scalar_one()
    py_status = derive_attendance_status(author_c, participant_c)

    assert sql_status == py_status.value, (author_c, participant_c)


@pytest.mark.parametrize(("author_c", "participant_c"), _STATUS_COMBINATIONS)
async def test_update_from_values_template_uses_new_flags(
    session: AsyncSession, author_c: bool | None, participant_c: bool | None
) -> None:
    """AC-03, CR 7.1 (C1): шаблон из docstring 7.2 читает НОВЫЕ значения.

    Первоначальный комментарий предписывал `UPDATE t SET a=..., status=<CASE>`
    одним `SET` — и это математически неверно: в SQL выражения `SET`
    вычисляются по СТАРОМУ кортежу. Воспроизведено на PostgreSQL 18:
    `UPDATE t SET a=true, p=true, status=<CASE>` даёт `status='pending'`.

    Здесь исполняется ИСПРАВЛЕННЫЙ шаблон — `UPDATE ... FROM (VALUES ...)`, где
    `CASE` ссылается на новые значения через `v.a`/`v.p`. Краснеет, если
    7.2 вернётся к `SET`-форме: там `status` станет `pending` при обоих `true`,
    и строка упадёт на `ck_attendance_status_consistency`.
    """
    author = await _create_user(session)
    place = await _create_place(session)
    card = await _create_card(session, author_id=author, place_id=place)
    participant = await _create_user(session)
    await _insert_attendance(
        session,
        card_id=card,
        participant_id=participant,
        author_confirmed=None,
        participant_confirmed=None,
    )

    expected = derive_attendance_status(author_c, participant_c)
    # Шаблон из docstring 7.2: подзапрос с алиасами колонок, чтобы
    # `STATUS_CASE_SQL` исполнялся ДОСЛОВНО и читал новые значения.
    # Проверено на PG 18: `UPDATE ... FROM (VALUES ...) AS v(a,p)` с голыми
    # именами падает «column does not exist», а `SET`-форма даёт старый кортеж.
    await session.execute(
        text(
            "UPDATE attendance AS t "
            "SET (author_confirmed, participant_confirmed, status, confirmed_at) = ( "
            "  SELECT v.author_confirmed, v.participant_confirmed, "
            f"         {STATUS_CASE_SQL}, "
            "         CASE WHEN v.author_confirmed IS NOT NULL "
            "                   AND v.participant_confirmed IS NOT NULL "
            "              THEN now() ELSE NULL END "
            "    FROM (VALUES (CAST(:a AS boolean), CAST(:p AS boolean))) "
            "         AS v(author_confirmed, participant_confirmed) "
            ") "
            "WHERE t.card_id = :card AND t.participant_id = :participant"
        ),
        {"a": author_c, "p": participant_c, "card": card, "participant": participant},
    )

    result = await session.execute(
        text("SELECT status FROM attendance WHERE card_id = :card AND participant_id = :p"),
        {"card": card, "p": participant},
    )

    assert result.scalar_one() == expected.value


