# --- CR 7.1: CHECK модели и миграции — одна и та же формула -------------------


async def test_model_check_expression_matches_database(session: AsyncSession) -> None:
    """AC-02/AC-08, CR 7.1 (HIGH): CHECK модели = CHECK в БД.

    Раньше расхождение между `STATUS_CONSISTENCY_SQL` (модель) и
    `_STATUS_CONSISTENCY` (миграция) не ловилось ничем: unit-тест сверял только
    ИМЯ ограничения, а `alembic check` слеп к тексту CHECK. Доказано мутацией:
    ослабление предиката ТОЛЬКО в модели оставляло «No new upgrade operations»
    и 29 зелёных тестов.

    Здесь модельный текст исполняется PostgreSQL: создаётся временная таблица
    с тем же набором колонок и `CHECK` из модели, после чего обе нормализованные
    формы (`pg_get_constraintdef`) сравниваются. PostgreSQL нормализует
    выражения одинаково для одинаковых типов, поэтому равенство текста —
    доказательство равенства формул, а не совпадения оформления.

    Краснеет при любой правке `STATUS_CONSISTENCY_SQL` без правки миграции
    (и наоборот).
    """
    await session.execute(
        text(
            "CREATE TEMP TABLE model_check_probe (\n"
            "    status character varying(16) NOT NULL,\n"
            "    author_confirmed boolean,\n"
            "    participant_confirmed boolean,\n"
            f"    CONSTRAINT probe_status_consistency CHECK ({STATUS_CONSISTENCY_SQL})\n"
            ") ON COMMIT DROP"
        )
    )

    result = await session.execute(
        text(
            "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint "
            "WHERE conname IN ('probe_status_consistency', 'ck_attendance_status_consistency')"
        )
    )
    definitions = {row[0]: row[1] for row in result}

    probe = definitions["probe_status_consistency"]
    actual = definitions["ck_attendance_status_consistency"]
    assert probe == actual, (
        f"CHECK модели разошёлся с CHECK в БД:\n  модель: {probe}\n  БД:     {actual}"
    )
