# --- AC-02: ограничения по именам ---------------------------------------------


async def test_attendance_constraints_match_expected_names(session: AsyncSession) -> None:
    """AC-02, §18.7: имена ограничений — часть контракта отката.

    Краснеет при двойном префиксе (`ck_attendance_ck_attendance_...`):
    `downgrade` снимает по имени и не нашёл бы объект.
    """
    # PostgreSQL 18 завёл ИМЕНОВАННЫЕ записи для `NOT NULL` (`contype='n'`):
    # они не являются ограничениями контракта и в `downgrade` не снимаются
    # по имени. Фильтр по типам — часть проверки, а не её ослабление: `p`, `u`,
    # `c`, `f` покрывают ровно то, что объявляют модель и миграция.
    result = await session.execute(
        text(
            "SELECT conname FROM pg_constraint WHERE conrelid = 'attendance'::regclass "
            "AND contype IN ('p', 'u', 'c', 'f') ORDER BY conname"
        )
    )

    assert sorted(row[0] for row in result) == sorted(EXPECTED_CONSTRAINTS)


