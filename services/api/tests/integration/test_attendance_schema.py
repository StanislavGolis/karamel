async def _insert_attendance(
    session: AsyncSession,
    *,
    card_id: int,
    participant_id: int,
    author_confirmed: bool | None,
    participant_confirmed: bool | None,
    status: str | None = None,
    confirmed_at: datetime | None = None,
) -> int:
    """Вставляет факт явки. `status` по умолчанию — из таблицы истинности."""
    if status is None:
        status = next(
            s for a, p, s in TRUTH_TABLE if a is author_confirmed and p is participant_confirmed
        )
    if confirmed_at is None and status != "pending":
        confirmed_at = datetime.now(UTC)

    row = await session.execute(
        text(
            "INSERT INTO attendance (card_id, participant_id, author_confirmed, "
            "participant_confirmed, status, confirmed_at) "
            "VALUES (:card, :participant, :author_c, :participant_c, :status, :confirmed_at) "
            "RETURNING id"
        ),
        {
            "card": card_id,
            "participant": participant_id,
            "author_c": author_confirmed,
            "participant_c": participant_confirmed,
            "status": status,
            "confirmed_at": confirmed_at,
        },
    )
    return int(row.scalar_one())


async def _columns(session: AsyncSession, table: str) -> dict[str, tuple[str, str]]:
    result = await session.execute(
        text(
            "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = :table"
        ),
        {"table": table},
    )
    return {row[0]: (row[1], row[2]) for row in result}


