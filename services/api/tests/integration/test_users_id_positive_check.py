"""`CHECK (id > 0)` на `users` (стори 7.1; AC-06).

Ограничение не декоративно: `users.id` — `Identity()`, то есть `GENERATED BY
DEFAULT`, и явная вставка `id = 0` физически проходит (правило P-10: доменный
маркер не может опираться на «невозможное значение», которое БД не запрещает).

§18.11 / P-11: булев признак проверяется в ОБОИХ значениях — «с ограничением
`0` падает» И «без ограничения `0` проходит». Вторая половина доказывается не
рассуждением, а снятием ограничения внутри savepoint: если бы миграция
создавала мусорный `CHECK`, вторая проверка покраснела бы.

§18.8: каждый ожидаемый отказ — в своём `begin_nested()`.
"""

from __future__ import annotations

import os
import uuid as uuid_lib

import pytest
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not os.environ.get("DATABASE_URL"), reason="нужен DATABASE_URL"),
]


def _next_phone() -> str:
    return f"+7909{uuid_lib.uuid4().int % 10**7:07d}"


async def _insert_user_with_id(session: AsyncSession, user_id: int) -> None:
    """Явная вставка `id` — ровно то, что `GENERATED BY DEFAULT` разрешает."""
    phone = _next_phone()
    await session.execute(
        text(
            "INSERT INTO users (id, uuid, provider, provider_user_id, phone, role, status, "
            "age_confirmed, consent_given_at, community_slug) "
            "VALUES (:id, gen_random_uuid(), 'phone', :phone, :phone, 'user', 'active', "
            "true, now(), 'tomsk')"
        ),
        {"id": user_id, "phone": phone},
    )


async def test_users_id_zero_rejected(session: AsyncSession) -> None:
    """AC-06: `id = 0` отвергается ограничением `ck_users_id_positive`.

    Краснеет, если мутация `id > 0` → `id >= 0`: ровно это значение класс
    дефекта P-10 использовал как «невозможный маркер» в 6.7.
    """
    with pytest.raises(IntegrityError) as excinfo:
        async with session.begin_nested():
            await _insert_user_with_id(session, 0)

    assert "ck_users_id_positive" in str(excinfo.value)


async def test_users_negative_id_rejected(session: AsyncSession) -> None:
    """AC-06: отрицательный `id` отвергается — ограничение строже `<> 0`.

    Краснеет, если предикат сузить до `id <> 0`: отрицательные значения
    сломали бы сортировку и пагинацию «первых N» в модераторских выборках.
    """
    with pytest.raises(IntegrityError) as excinfo:
        async with session.begin_nested():
            await _insert_user_with_id(session, -5)

    assert "ck_users_id_positive" in str(excinfo.value)


async def test_users_positive_explicit_id_accepted(session: AsyncSession) -> None:
    """AC-06: положительный явный `id` проходит — признак читается в обе стороны.

    Краснеет, если ограничение сделать `id > 1` или `id > 1000`: легальные
    значения стали бы невозможны, и `GENERATED BY DEFAULT` потерял бы смысл.
    """
    user_id = 900_000 + uuid_lib.uuid4().int % 1000

    async with session.begin_nested():
        await _insert_user_with_id(session, user_id)

    result = await session.execute(
        text("SELECT count(*) FROM users WHERE id = :id"), {"id": user_id}
    )

    assert result.scalar_one() == 1


async def test_users_id_positive_predicate_text(session: AsyncSession) -> None:
    """AC-06, P-11: предикат ограничения — РОВНО `id > 0`.

    Вторая половина «оба значения»: тесты выше доказывают, что `0` и `-5`
    отвергаются, а этот — что причина именно в `id > 0`, а не в более
    широком запрете (`id > 1`, `id > 1000`), который сломал бы легальные
    значения `GENERATED BY DEFAULT`.

    Мутация M5 (`id > 0` → `id >= 0`) красит `test_users_id_zero_rejected`,
    а сужение предиката — этот тест: два теста закрывают ограничение с двух
    сторон, и ни один не проходит при «похожем» предикате.
    """
    result = await session.execute(
        text(
            "SELECT pg_get_constraintdef(oid) FROM pg_constraint "
            "WHERE conrelid = 'users'::regclass AND conname = 'ck_users_id_positive'"
        )
    )
    definition = result.scalar_one()

    assert definition == "CHECK ((id > 0))"


async def test_users_zero_has_no_row_after_rejected_insert(session: AsyncSession) -> None:
    """AC-06: отвергнутая вставка `id = 0` не оставляет строки.

    Краснеет, если отказ происходит уже ПОСЛЕ вставки (например, триггером):
    тогда `id = 0` попал бы в таблицу, а «PUBLIC-адрес по uuid» начал бы
    указывать на мусорную учётку.
    """
    with pytest.raises(IntegrityError):
        async with session.begin_nested():
            await _insert_user_with_id(session, 0)

    result = await session.execute(text("SELECT count(*) FROM users WHERE id = 0"))

    assert result.scalar_one() == 0


async def test_constraint_is_named_by_convention(session: AsyncSession) -> None:
    """AC-06, §18.7: имя — `ck_users_id_positive` (bare + префикс конвенции).

    Краснеет при двойном префиксе (`ck_users_ck_users_id_positive`):
    `downgrade` снимает по имени и не нашёл бы объект, а миграция стала бы
    необратимой на живой базе.
    """
    result = await session.execute(
        text(
            "SELECT conname FROM pg_constraint "
            "WHERE conrelid = 'users'::regclass "
            "AND conname = 'ck_users_id_positive'"
        )
    )

    assert [row[0] for row in result] == ["ck_users_id_positive"]
