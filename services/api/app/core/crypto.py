"""Прикладное шифрование переписки чата (стори 6.1; AC-04, NFR31).

AES-256-GCM (`cryptography.hazmat.primitives.ciphers.aead.AESGCM`):
аутентифицированное шифрование — подмена ЛЮБОГО байта блоба обнаруживается
тегом, а не проходит как «другое сообщение». Для переписки это важнее
режимов без аутентификации (CBC/CTR): без тега атакующий с доступом к БД
мог бы подменять байты шифртекста, и получатель увидел бы валидный,
но чужой текст.

**Формат блоба:** `nonce(12) ‖ ciphertext(N) ‖ tag(16)`. Один столбец
`messages.body BYTEA` вместо трёх (nonce/ciphertext/tag): три колонки
обязаны меняться вместе, и частично записанная строка дала бы блоб,
который невозможно расшифровать, но который БД считает валидным.

**AAD привязывает блоб к чату и автору (CR 6.1, находка 1).** Тег GCM
аутентифицирует `chat_id` и `sender_id` вместе с текстом. Без этого валидный
блоб можно ПЕРЕНЕСТИ: `INSERT INTO messages (chat_id, sender_id, body)`
с блобом из другого чата расшифровался бы без ошибки, и участник прочитал бы
чужое сообщение как своё. AAD — не секрет, он лежит рядом в тех же колонках,
и его подмена ломает тег.

**Ключ в БД не хранится** (NFR31): берётся из настроек
(`Settings.chat_message_key`). Из человекочитаемой строки он превращается
в 32 байта через `sha256` — AES-256 требует ровно 32 байта, а конфиг
остаётся сравнимой с `jwt_secret` строкой (валидатор длины ≥32).

**Nonce — 12 случайных байт `secrets.token_bytes` на КАЖДОЕ сообщение.**
Повтор nonce при GCM с одним ключом раскрывает XOR двух plaintext'ов и
позволяет подделать тег; детерминированный nonce (например из `chat_id`)
дал бы ровно этот дефект на втором сообщении того же чата.

**Смена ключа = потеря старых сообщений.** Ротация (хранение версии ключа
в блобе) — долг эпика 7; в 6.1 ключ один, и это записано явно, чтобы
деплой не менял `CHAT_MESSAGE_KEY` «на всякий случай».
"""

from __future__ import annotations

import hashlib
import secrets

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from app.core.config import get_settings

# AC-04: 12 байт — рекомендованный размер nonce для GCM (96 бит).
_NONCE_SIZE = 12
# AC-04: тег GCM — 16 байт. Минимальная длина корректного блоба = nonce + tag.
_TAG_SIZE = 16
_MIN_BLOB_SIZE = _NONCE_SIZE + _TAG_SIZE

# CR 6.1: верхняя граница тела. Пустое сообщение отбивает схема 6.4, но
# «сообщение на 200 МБ» прошло бы и схему, и `BYTEA`: страница истории
# тянет блоб целиком в память, бэкапы и репликация раздуваются. Предел
# держится в двух местах — здесь (быстрый отказ без обращения к БД) и
# `CHECK octet_length(body) <= ...` в схеме (обход сервиса).
MAX_BODY_BYTES = 65_535
# CR 6.1, находка 4: минимальная длина ключа проверяется ЗДЕСЬ, а не только
# валидатором настроек: `key=` — публичный параметр, и `key="a"` дал бы
# полноценный AES-ключ из одного символа, обойдя весь контроль энтропии.
MIN_KEY_CHARS = 32


def _derive_key(secret: str) -> bytes:
    """Превращает строку настройки в 32-байтовый ключ AES-256.

    D-6.1-4: `sha256` детерминирован и даёт ровно 32 байта. KDF с солью
    здесь не нужен: секрет — не пароль человека, а случайная строка из
    окружения, и соль пришлось бы хранить рядом с блобом (в БД, NFR31).

    CR 6.1, находка 10: строка нормализуется `strip()` и ЗДЕСЬ. Валидатор
    настроек проверяет обрезанное значение; без той же нормализации здесь
    `CHAT_MESSAGE_KEY` с завершающим переводом строки (типовая ошибка
    docker-compose) давал бы другой ключ, чем тот же секрет без него.
    """
    normalized = (secret or "").strip()
    if not normalized:
        raise ValueError("CHAT_MESSAGE_KEY не задан: шифрование невозможно")
    if len(normalized) < MIN_KEY_CHARS:
        raise ValueError(
            f"CHAT_MESSAGE_KEY короче {MIN_KEY_CHARS} символов: ключ перебирается офлайн"
        )
    return hashlib.sha256(normalized.encode("utf-8")).digest()


def _aad(*, chat_id: int, sender_id: int | None) -> bytes:
    """Дополнительные аутентифицируемые данные: «сообщение в этом чате от этого автора».

    CR 6.1, находка 1: без AAD блоб переносим между чатами (см. докстринг модуля).
    Значения не секретны — они лежат в тех же колонках, — но их подмена
    ломает тег GCM, поэтому «вставить чужой блоб в свой чат» перестаёт работать.

    **CR 6.7 (находка A-1): автор кодируется ДОМЕНОМ, а не числом.** Прежняя
    версия подставляла для системного сообщения константу `0`, обосновывая
    это тем, что `users.id` начинается с 1. Это ЛОЖНО на уровне схемы:
    `users.id` объявлен `Identity()` — в PostgreSQL это `GENERATED BY DEFAULT`,
    а `BY DEFAULT` разрешает ЯВНУЮ вставку `id = 0` (проверено фактом:
    `INSERT INTO users (id, ...) VALUES (0, ...)` проходит). Тогда AAD
    системного сообщения совпал бы с AAD пользователя 0, и блоб системного
    можно было бы выдать за сообщение этого пользователя (и наоборот) —
    ровно та подмена, от которой AAD и защищает.

    Поэтому маркер системного сообщения — СТРОКА `system` в отдельной позиции
    домена, а не число в позиции автора: `None` (нет автора) не может совпасть
    ни с одним `int`. Формат AAD обычного сообщения НЕ изменился
    (`chat:{id}|sender:{id}`), поэтому уже записанные блобы читаются как есть.
    """
    sender_domain = "system" if sender_id is None else str(sender_id)
    return f"chat:{chat_id}|sender:{sender_domain}".encode()


def encrypt_message_body(
    plaintext: str,
    *,
    chat_id: int,
    sender_id: int | None,
    key: str | None = None,
) -> bytes:
    """AC-04, NFR31: шифрует текст сообщения в блоб `nonce ‖ ct ‖ tag`.

    `chat_id`/`sender_id` обязательны: они входят в AAD, и без них блоб
    становится переносимым между чатами (CR 6.1). `key` — только для тестов
    (два разных ключа → `InvalidTag`); в рабочем коде берётся
    `Settings.chat_message_key`.

    Пустой plaintext и тело длиннее `MAX_BODY_BYTES` отвергаются `ValueError`:
    пустое сообщение — ошибка схемы 6.4, а «сообщение на 200 МБ» прошло бы
    и схему, и `BYTEA` (страница истории тянет его целиком в память).
    """
    if not plaintext:
        raise ValueError("Пустое тело сообщения не шифруется")
    encoded = plaintext.encode("utf-8")
    if len(encoded) > MAX_BODY_BYTES:
        raise ValueError(f"Тело сообщения длиннее {MAX_BODY_BYTES} байт: {len(encoded)}")
    secret = key if key is not None else get_settings().chat_message_key
    aesgcm = AESGCM(_derive_key(secret))
    # AC-04: НОВЫЙ nonce на каждое сообщение — не переиспользуется никогда.
    nonce = secrets.token_bytes(_NONCE_SIZE)
    sealed = aesgcm.encrypt(nonce, encoded, _aad(chat_id=chat_id, sender_id=sender_id))
    # `AESGCM.encrypt` возвращает `ciphertext ‖ tag`; склеиваем с nonce.
    return nonce + sealed


def decrypt_message_body(
    blob: bytes,
    *,
    chat_id: int,
    sender_id: int | None,
    key: str | None = None,
) -> str:
    """AC-04: расшифровывает блоб. `InvalidTag` — блоб подменён, перенесён
    в другой чат/от другого автора или ключ чужой.

    Слишком короткий блоб отвергается `ValueError`, а не `InvalidTag`:
    «битые данные» и «неверный ключ/подмена» — разные ошибки, и вызывающий
    код (6.4) обрабатывает их по-разному. Не-UTF8 plaintext после успешной
    аутентификации — тоже `ValueError` (CR 6.1): записанный не через
    `encrypt_message_body` блоб не должен превращаться в `500` из
    `UnicodeDecodeError` при каждом чтении страницы.
    """
    if len(blob) <= _MIN_BLOB_SIZE:
        raise ValueError(f"Блоб короче nonce+tag ({len(blob)} <= {_MIN_BLOB_SIZE}): не шифртекст")
    secret = key if key is not None else get_settings().chat_message_key
    aesgcm = AESGCM(_derive_key(secret))
    nonce = blob[:_NONCE_SIZE]
    sealed = blob[_NONCE_SIZE:]
    # `InvalidTag` пробрасывается как есть (CR 6.1, находка 9: пустой
    # `except: raise` убран — он ничего не делал). Это библиотечное
    # исключение, и 6.4 различает его по типу, не импортируя нашу обёртку.
    plaintext = aesgcm.decrypt(nonce, sealed, _aad(chat_id=chat_id, sender_id=sender_id))
    try:
        return plaintext.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ValueError(
            "Тело сообщения не является UTF-8: блоб записан не через encrypt_message_body"
        ) from exc
