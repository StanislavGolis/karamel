"""Схемы API настроек канала уведомлений (стори 9.3; AC-01, AC-02).

**`PATCH` переключает ОДИН тип** (D-9.3-8): `{type, enabled}`. Полная замена
набора (`PUT`) отклонена: UI переключает один тип, а замена заставила бы
клиент присылать и неотключаемые типы, дав ложный `409` на весь запрос из-за
одного элемента, который и так нельзя выключить.

**Чего здесь НЕТ намеренно.**

- Перечня допустимых `type` в `Literal[...]`. Валидация значения — в сервисе
  (`UnknownNotificationTypeError`), иначе неизвестный тип давал бы `422` от
  FastAPI с телом `{"detail": [...]}`, а не проектный конверт
  `{"code": "invalid_notification_type"}`. Один код ошибки на весь домен
  важнее «красивой» аннотации.
- Поля `required` во входной схеме: это вычисляемое сервером свойство типа,
  и его наличие в теле запроса дало бы клиенту возможность «объявить» тип
  обязательным.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict

__all__ = [
    "NotificationSettingRead",
    "NotificationSettingsListResponse",
    "NotificationSettingsUpdate",
]


class NotificationSettingRead(BaseModel):
    """AC-01: один тип в ответе — `type`, `enabled`, `required`.

    `required=True` — «нельзя отключить» (D-9.3-5). UI рисует такой
    переключатель включённым и недоступным; API отвечает `409` при попытке
    выключить. Клиент обязан читать `required`, а не выводить его сам:
    перечень обязательных — продуктовое решение, и его изменение не должно
    требовать релиза фронта.
    """

    #: NFR60: строковое значение типа (`сущность.действие`).
    type: str
    #: Текущее состояние: `False` — тип отключён (opt-out-строка есть).
    enabled: bool
    #: D-9.3-5: `True` — тип отключать запрещено (FR38/FR39).
    required: bool


class NotificationSettingsListResponse(BaseModel):
    """AC-01: ПОЛНЫЙ перечень 11 типов в фиксированном порядке.

    Клиент не хранит список типов у себя (D-9.3-8): локальная копия тихо
    отстала бы от серверной, а NFR60 велит игнорировать неизвестное — то есть
    новый тип не появился бы в UI никогда.
    """

    items: list[NotificationSettingRead]


class NotificationSettingsUpdate(BaseModel):
    """AC-01: тело `PATCH` — `{type, enabled}` для ОДНОГО типа (D-9.3-8).

    `extra="forbid"`: лишнее поле в теле — признак расхождения клиента и
    сервера, и молча его проглотить значит скрыть баг. `enabled` объявлен
    строго `bool`: строка `"false"` не должна включить тип (Pydantic иначе
    привёл бы её к `True` в нестрогом режиме — тихая инверсия, мутация M5).
    """

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    #: Тип уведомления. Проверка вхождения — в сервисе (см. docstring модуля).
    #:
    #: **Ни `min_length`, ни `max_length`.** Любое ограничение длины в Pydantic
    #: дало бы `422 invalid_request` от FastAPI — ДРУГОЙ код, чем
    #: `invalid_notification_type`, и клиент не смог бы показать текст
    #: («неизвестный тип» вместо «поле пустое»). AC-01 требует один код на
    #: значение вне перечня/формы, поэтому форму проверяет сервис.
    type: str
    #: `False` — отключить, `True` — включить.
    enabled: bool
