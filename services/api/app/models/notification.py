"""Модель адресного уведомления `notifications` (стори 7.3; AC-01).

**Минимальная таблица-аутбокс, не центр уведомлений** (решение 1 пакета).
Полный центр с UI, настройками и группировкой — эпик 9. Здесь только то, без
чего 7.3 невыполнима: адресный запрос «подтвердите явку» нельзя доставить
в канал чата, которого у участника может не быть (AC-04).

**`TimestampMixin` НЕ наследуется** (X-7.1-1). Миксин даёт `updated_at`,
а путь записи этой таблицы — сырой `INSERT ... SELECT` из воркера:
`onupdate` ORM на нём не срабатывает никогда, и колонка осталась бы
`NULL`/старой навсегда — ложный аудит «когда менялось». `created_at`
объявлен явно с `server_default=func.now()`, как в `attendance`.

**`uuid` добавлен в стори 9.1** (AC-01, project-context §7). В 7.3 его не
было намеренно: таблица не адресовалась по API, публичный адрес давала
карточка. С 9.1 уведомление — самостоятельный ресурс с отметкой прочтения,
поэтому нужен собственный публичный ID. `server_default` ОСТАЁТСЯ: строки
пишет воркер сырым `INSERT` без `uuid`, и без дефолта вставка падала бы.

**`UNIQUE` нет намеренно** (X-7.3-2). Идемпотентность запроса держится на
CAS карточки (`event_cards.attendance_prompted_at`, ADR-15), а не на
ограничении таблицы: ограничение без запроса только замедлило бы вставку,
но не доказало бы «ровно один запрос» — это свойство транзакции карточки,
а не строки уведомления.

**`id > 0` — не декоративно** (D-TD-2, P-10). `Identity()` — это
`GENERATED BY DEFAULT`, явная вставка `id = 0` физически проходит; в 6.7
на этом построен класс дефекта «невозможный id». Нужны ОБА: `Identity()`
для автонумерации и `CHECK` как единственная защита от явной вставки.
"""

from __future__ import annotations

import uuid as uuid_lib
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    PrimaryKeyConstraint,
    String,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base
from app.models.enums import NOTIFICATION_TYPES
from app.schemas.ws import TYPE_PATTERN

#: AC-01: `type` — `сущность.действие` (NFR60). Форма берётся из
#: `app/schemas/ws.py`, а не дублируется регуляркой: `attendance.request`
#: обязан проходить и здесь, и в конверте WS — третья копия regex разошлась
#: бы при первом же новом событии (класс дефекта 4.1).


#: AC-02 стори 9.1: `col IN ('a','b')` из кортежа значений. Копия — общий
#: существующий долг (`chat.py`, `attendance.py`, `access_log.py`, `sanction.py`).
def _in_clause(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(str(v)) for v in values)})"


class Notification(Base):
    """Адресное уведомление пользователя (аутбокс воркера).

    Одна строка — один адресат одного события. Для 7.3: `type='attendance.request'`,
    адресаты — автор карточки (один раз) и каждый участник принятой заявки.
    """

    __tablename__ = "notifications"

    # AC-01, D-TD-2: `Identity()` + `CHECK (id > 0)`. Оба обязательны:
    # `Identity()` даёт `GENERATED BY DEFAULT`, и явная вставка `id = 0`
    # прошла бы без ограничения (P-10, прецедент 6.7).
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)

    # AC-01 стори 9.1: публичный ID уведомления. Адресуется по API (отметка
    # прочтения 9.3). `server_default` обязателен: воркер 7.3 пишет строки
    # сырым `INSERT` без `uuid`, и без дефолта вставка упала бы с NotNullViolation
    # (проверено тестом S09, D-9.1-8).
    uuid: Mapped[uuid_lib.UUID] = mapped_column(
        PGUUID(as_uuid=True), nullable=False, server_default=text("gen_random_uuid()")
    )

    # AC-01: адресат. `CASCADE` — удаление пользователя уносит его уведомления:
    # адресный запрос без адресата не имеет смысла и не должен переживать
    # субъекта (ADR-07, ретенция).
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )

    # AC-01, NFR60: `сущность.действие` — только нижний регистр и точка.
    # `String(64)` с запасом: `attendance.request` = 18 символов, но тип
    # описывает домен, а не одну эту стори.
    type: Mapped[str] = mapped_column(String(64), nullable=False)

    # AC-01, AC-11, NFR60: нагрузка — ОБЪЕКТ, не массив и не скаляр.
    # Безличность (решение 3 пакета): ни `user_id`, ни `author_id`, ни имён —
    # только `card_uuid` и `starts_at`. Проверяется рекурсивным обходом ключей.
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)

    # AC-01: `created_at` ЯВНО, миксин не наследуется (X-7.1-1).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # AC-01: доставка и прочтение — эпик 9. В 7.3 колонки только создаются:
    # `delivered_at IS NULL` и есть «ещё не доставлено» (граница 9.х).
    delivered_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    read_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    __table_args__ = (
        # AC-01: имя PK строится конвенцией (`pk_notifications`).
        PrimaryKeyConstraint("id"),
        # AC-01 стори 9.1: публичный адрес уникален (`uq_notifications_uuid`).
        UniqueConstraint("uuid"),
        # AC-01, D-TD-2: единственная защита от явной вставки неположительного id.
        CheckConstraint("id > 0", name="id_positive"),
        # AC-01, NFR60: форма типа. Имя — `ck_notifications_type_format`
        # (`naming_convention` добавит префикс `ck_notifications_`).
        CheckConstraint(f"type ~ '{TYPE_PATTERN}'", name="type_format"),
        # AC-02 стори 9.1: ПЕРЕЧЕНЬ допустимых типов, поверх проверки формы.
        # Два ограничения ловят разное (D-9.1-3): регекс — опечатку формы
        # (`BAD`), перечень — валидную по форме чужую сущность (`foo.bar`).
        # Второе критично: NFR60 велит клиенту ИГНОРИРОВАТЬ неизвестный тип,
        # поэтому ошибку в имени не заметит никто.
        CheckConstraint(_in_clause("type", NOTIFICATION_TYPES), name="type"),
        # AC-01, NFR60: payload — объект. `jsonb_typeof` возвращает строку
        # типа, поэтому сравнение с `'object'` безопасно и на массиве даёт
        # ложь, а не `NULL` (в отличие от `payload ? 'key'`).
        CheckConstraint("jsonb_typeof(payload) = 'object'", name="payload_object"),
        # AC-01: порядок доставки. `delivered_at` не может быть раньше
        # создания: это утверждало бы доставку до события.
        CheckConstraint("delivered_at >= created_at", name="delivery_order"),
        # AC-01, CR 7.3 H-2: прочтение не может быть раньше доставки — и не
        # может существовать БЕЗ доставки. Прежняя форма `read_at >=
        # delivered_at` этого не запрещала: при `delivered_at IS NULL`
        # выражение даёт `UNKNOWN`, а `CHECK` отвергает только `FALSE`
        # (проверено INSERT на живой БД: `read_at` без доставки проходил).
        # Бикондиционал явно перечисляет оба допустимых состояния.
        CheckConstraint(
            "(delivered_at IS NULL AND read_at IS NULL) "
            "OR (delivered_at IS NOT NULL AND (read_at IS NULL OR read_at >= delivered_at))",
            name="read_order",
        ),
        # AC-01: будущий список «мои непрочитанные» эпика 9 — предикат
        # `user_id = :u ORDER BY delivered_at`. Составной, по решению
        # пользователя (открытый вопрос 2 стори: партиальный — при объёме 9).
        Index("ix_notifications_user_delivery", "user_id", "delivered_at"),
        # AC-03 стори 9.1: выдача непрочитанных — `WHERE user_id = :u AND
        # read_at IS NULL`. Состав `(user_id, read_at)` из AC; партиальный
        # вариант отклонён до реального объёма (D-9.1-10).
        Index("ix_notifications_user_read", "user_id", "read_at"),
    )


__all__ = ["Notification"]
