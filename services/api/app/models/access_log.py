"""Модель аудита доступа `access_logs` (стори 8.6; AC-01, AC-06, AC-08).

**Зачем таблица, а не только `structlog`.** NFR32 требует «холодное хранилище;
содержит: кто, когда, к какому диалогу / карточке». Лог процесса уходит в
ротацию контейнера, и из него нельзя ответить «кто открывал переписку этого
человека за полгода» — а NFR42 требует шесть месяцев.

**Почему НИ ОДНОГО FK** (D-92). `ON DELETE SET NULL` обнулял бы `chat_uuid`
при удалении чата (каскад от карточки, 8.2), и запись перестала бы отвечать на
вопрос, ради которого создана. Append-only лог фиксирует факт о ПРОШЛОМ и не
зависит от жизненного цикла того, что фиксирует: UUID — публичные стабильные
адреса (D-2), их достаточно для расследования.

**Почему нет колонки для текста** (D-91). Утечка невыразима на уровне схемы:
нельзя «забыть отфильтровать» поле, которого нет. Ни `body`, ни `reason`,
ни `message` — только идентификаторы и `message_count` (NFR27).

**`TimestampMixin` НЕ наследуется.** Путь записи — сырой `INSERT` через
репозиторий, на котором ORM-`onupdate` не срабатывает: `updated_at` остался бы
`NULL` навсегда. У аудита и нет «обновления» — он append-only; колонка названа
`created_at` по домену (момент доступа).

**Триггера append-only нет** (D-84). Тест на текст SQL-констант ловит появление
`UPDATE`/`DELETE` в коде; триггер молча блокировал бы легитимную очистку по
ретенции (эпик 10), которую придётся делать осознанным `DELETE`.
"""

from __future__ import annotations

import uuid as uuid_lib
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Identity,
    Index,
    PrimaryKeyConstraint,
    SmallInteger,
    String,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base

#: AC-01, AC-08: домен действий. `CHECK` вместо нативного enum (стиль проекта,
#: D-3): набор значений меняется одной миграцией, без `ALTER TYPE`.
ACCESS_ACTIONS: tuple[str, ...] = ("fragment_read", "card_read")


def _in_clause(column: str, values: tuple[str, ...]) -> str:
    """Собирает `CHECK (col IN ('a','b'))`. Копия — существующий долг `deferred-work.md`."""
    joined = ", ".join(f"'{v}'" for v in values)
    return f"{column} IN ({joined})"


class AccessLog(Base):
    """Факт доступа модератора к приватным данным: переписке или карточке."""

    __tablename__ = "access_logs"

    # AC-01, P-10: `Identity()` = `GENERATED BY DEFAULT`, явная вставка id=0
    # физически проходит — `CHECK (id > 0)` не декоративен.
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)

    # AC-01: публичный адрес записи. `server_default` — запись идёт сырым
    # `INSERT` без ORM-дефолтов.
    uuid: Mapped[uuid_lib.UUID] = mapped_column(
        PGUUID(as_uuid=True), nullable=False, server_default=text("gen_random_uuid()")
    )

    # AC-01, D-92: автор доступа. `NOT NULL` без FK: у факта всегда есть
    # модератор, и удаление его аккаунта не должно менять запись.
    moderator_uuid: Mapped[uuid_lib.UUID] = mapped_column(PGUUID(as_uuid=True), nullable=False)

    # AC-01, AC-08: что открывали — переписку или карточку.
    action: Mapped[str] = mapped_column(String(24), nullable=False)

    # AC-08: пользователь, чью карточку открыли. `NULL` у `fragment_read`:
    # у доступа к переписке адресат — диалог, а не отдельный пользователь.
    subject_uuid: Mapped[uuid_lib.UUID | None] = mapped_column(PGUUID(as_uuid=True))

    # AC-01: цель доступа. Все три `NULL`-able: у `card_read` их нет.
    report_uuid: Mapped[uuid_lib.UUID | None] = mapped_column(PGUUID(as_uuid=True))
    chat_uuid: Mapped[uuid_lib.UUID | None] = mapped_column(PGUUID(as_uuid=True))
    card_uuid: Mapped[uuid_lib.UUID | None] = mapped_column(PGUUID(as_uuid=True))

    # AC-03: сколько сообщений отдано. `NULL` у `card_read`. `SMALLINT`: FR40
    # ограничивает фрагмент десятью, запас до 32767 стоит два байта.
    message_count: Mapped[int | None] = mapped_column(SmallInteger)

    # AC-06, NFR42: момент доступа. По нему считается ретенция (эпик 10).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # AC-01, NFR32: исходный путь запроса — для разбора «как именно открыли».
    # Строка, а не enum: маршрут меняется чаще домена действий.
    route: Mapped[str | None] = mapped_column(String(128))

    __table_args__ = (
        # AC-01: имя PK строится конвенцией (`pk_access_logs`).
        PrimaryKeyConstraint("id"),
        # AC-01: единственная защита от явной вставки неположительного id.
        CheckConstraint("id > 0", name="id_positive"),
        # AC-01: публичный адрес уникален. Имя дословно как в `0029`.
        UniqueConstraint("uuid", name="uq_access_logs_uuid"),
        # AC-01, AC-08: домен действия. Имя `action_allowed` — как в миграции.
        CheckConstraint(_in_clause("action", ACCESS_ACTIONS), name="action_allowed"),
        # AC-06, NFR42: индекс ретенции. Имя и состав ДОЛЖНЫ совпадать с `0029`
        # дословно (P-13): модель и миграция — две копии одной схемы.
        Index("ix_access_logs_created_at", "created_at"),
        # Разбор инцидента: «что открывал этот модератор». Составной с `DESC`.
        Index(
            "ix_access_logs_moderator_uuid_created_at",
            "moderator_uuid",
            text("created_at DESC"),
        ),
    )


__all__ = ["ACCESS_ACTIONS", "AccessLog"]
