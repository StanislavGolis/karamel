"""Модель санкции `sanctions` (стори 8.1, AC-07).

**Зачем отдельная таблица, а не поля в `reports`.** Одна жалоба — одно решение
(`UNIQUE (report_id)`), но санкция живёт дольше жалобы: карточка 8.5 показывает
ВСЮ историю пользователя, включая санкции по жалобам, которые уже не в очереди.

**`moderator_id` — `ON DELETE SET NULL`, не `CASCADE`.** Санкция — факт
состоявшегося решения; удаление аккаунта модератора не отменяет её. Обвиняемый
же удаляется каскадом: санкция без субъекта не адресуется.

**`TimestampMixin` НЕ наследуется** (X-7.1-1). Путь записи 8.4 — сырой
`INSERT`, на котором ORM-`onupdate` не срабатывает: `updated_at` остался бы
`NULL` навсегда — ложный аудит «когда менялось». Колонка названа `created_at`
по домену (момент решения).

**`revoked_at` не вводится** (D-17): в эпике 8 нет стори о снятии санкции, а
активность бана выводится `EXISTS (type='ban')`. Добавление срока без
потребителя создало бы поле, о котором никто не помнит.

**Рейтинга, кармы и агрегатов нет** (NFR54): санкция — запись о последствии,
а не игровая метрика.
"""

from __future__ import annotations

import uuid as uuid_lib
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    PrimaryKeyConstraint,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base
from app.models.enums import SanctionType

#: AC-07: домен вида санкции. `dismissed` сюда НЕ входит — закрытие без санкции.
SANCTION_TYPES: tuple[str, ...] = tuple(t.value for t in SanctionType)


def _in_clause(column: str, values: tuple[str, ...]) -> str:
    """Собирает `CHECK (col IN ('a','b'))`. Девятая копия — долг `deferred-work.md`."""
    joined = ", ".join(f"'{v}'" for v in values)
    return f"{column} IN ({joined})"


class Sanction(Base):
    """Последствие нарушения: предупреждение или бан, вынесенное модератором."""

    __tablename__ = "sanctions"

    # AC-07, P-10: `Identity()` = `GENERATED BY DEFAULT`, явная вставка id=0
    # физически проходит — `CHECK (id > 0)` не декоративен.
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)

    # AC-07: публичный адрес. Адресуется карточкой 8.5; `server_default` —
    # потому что запись идёт сырым `INSERT` без ORM-дефолтов.
    uuid: Mapped[uuid_lib.UUID] = mapped_column(
        PGUUID(as_uuid=True), nullable=False, server_default=text("gen_random_uuid()")
    )

    # AC-07: обвиняемый. `CASCADE` — санкция без субъекта не адресуется.
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )

    # AC-07: предмет решения. `UNIQUE` ниже — единственная защита от двух
    # решений по одной жалобе (8.4: `409`), предпроверка запрещена (P-3).
    report_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("reports.id", ondelete="CASCADE"), nullable=False
    )

    # AC-07: кто вынес. `SET NULL` — решение остаётся фактом при удалении
    # аккаунта модератора.
    moderator_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )

    # AC-07: вид санкции. `String(16)` с запасом: `warning` = 7.
    type: Mapped[str] = mapped_column(String(16), nullable=False)

    # AC-07: причина для обвиняемого (FR38/FR39). Обязательна: санкция без
    # объяснения неотличима от ошибки модератора.
    reason: Mapped[str] = mapped_column(Text, nullable=False)

    # AC-07, X-7.1-1: момент решения. `created_at`, не `updated_at`.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        PrimaryKeyConstraint("id"),
        # AC-07, P-10: защита от явной вставки неположительного id.
        CheckConstraint("id > 0", name="id_positive"),
        # AC-07: публичный адрес уникален (`uq_sanctions_uuid`).
        UniqueConstraint("uuid"),
        # AC-07: одно решение на жалобу. `ON CONFLICT (report_id)` в 8.4
        # резолвится по этому ограничению.
        UniqueConstraint("report_id"),
        # AC-07: вид санкции.
        CheckConstraint(_in_clause("type", SANCTION_TYPES), name="type"),
        # AC-08: история пользователя для карточки 8.5. Составной, с `DESC`:
        # выборка всегда `WHERE user_id = :id ORDER BY created_at DESC`
        # (keyset по правилу D-9).
        Index("ix_sanctions_user_id_created_at", "user_id", text("created_at DESC")),
    )


__all__ = ["SANCTION_TYPES", "Sanction"]
