"""Модель чата компании `chats` (стори 6.1; AC-01, AC-02, AC-09).

AC-01 (FR30, FR85, FR86; ADR-04): один чат на карточку события. Инвариант
живёт в БД (`UNIQUE event_card_id`), а не в соглашении кода: два чата на одну
встречу разошлись бы по составу участников, и «компания» перестала бы быть
определённой.

AC-02: колонок участников (`user_a_id`/`user_b_id`) НЕТ намеренно (ADR-04).
Компания — 2–6 человек: в две колонки она не влезает, а денормализованный
список участников разошёлся бы с `join_requests` при отмене участия (5а.6)
и при замене выбранного (5б.3). Состав вычисляется запросом (стори 6.3) из
`join_requests.status='selected'` (режим заявок) либо из присоединившихся
(открытый набор).

D-2: `id` — внутренний `bigint`, наружу не выходит никогда; публичный
идентификатор — `uuid`. FK из `messages` идёт на `id`: индекс по `bigint`
дешевле, чем по `uuid`.

Контракт стори 5б.2 (D-5b.2-1): `chats.uuid = event_cards.chat_uuid`. Значение
УЖЕ создано выбором автора одним `UPDATE`; стори 6.1 таблицу создаёт, но
данными не заполняет и новое значение не генерирует.

**Стори 8.2 (D-21): `status` — состояние ДИАЛОГА, не участника.** Скрытие по
жалобе относится к обеим сторонам сразу (FR37), поэтому живёт одной строкой
чата, а не персональным флагом: персональный флаг дал бы расхождение списков
сторон и не выразил бы «общение прекратилось у обоих».
"""

from __future__ import annotations

import uuid as uuid_lib

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    Identity,
    String,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, TimestampMixin

#: AC-01 стори 8.2: домен состояния чата. `hidden` — диалог скрыт жалобой
#: (FR37) и не показывается НИ ОДНОЙ стороне. Кортеж — единственный источник
#: для `CHECK`: третья копия разошлась бы при добавлении значения.
CHAT_STATUSES: tuple[str, ...] = ("active", "hidden")


def _in_clause(column: str, values: tuple[str, ...]) -> str:
    """`col IN ('a','b')` из кортежа. Копия — существующий долг `deferred-work.md`."""
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


class Chat(Base, TimestampMixin):
    """Чат компании по карточке события.

    AC-01: `created_at`/`updated_at` приходят из `TimestampMixin`
    (`timestamptz` + серверный `now()`), дублировать их не нужно.
    """

    __tablename__ = "chats"

    # D-2: внутренний PK. `Identity()` — `GENERATED BY DEFAULT AS IDENTITY`,
    # а не `serial`: `serial` создаёт неявную последовательность без владельца.
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)

    # AC-01: публичный идентификатор. Значение приходит из
    # `event_cards.chat_uuid` (контракт 5б.2) — здесь НЕ генерируется.
    uuid: Mapped[uuid_lib.UUID] = mapped_column(PGUUID(as_uuid=True), nullable=False)

    # AC-01: один чат на карточку. `UNIQUE` объявлен в `__table_args__`,
    # а не в `mapped_column`, чтобы имя ограничения шло через конвенцию.
    event_card_id: Mapped[int] = mapped_column(
        BigInteger,
        ForeignKey("event_cards.id", ondelete="CASCADE"),
        nullable=False,
    )

    # AC-01 стори 8.2, D-21: состояние диалога. `server_default` обязателен:
    # существующие чаты созданы без колонки и должны остаться видимыми.
    # `default` нужен ORM-пути (вставка через модель), `server_default` —
    # сырому `INSERT` в обход ORM (тот же довод, что у `reports.status`).
    status: Mapped[str] = mapped_column(
        String(16), nullable=False, default="active", server_default=text("'active'")
    )

    __table_args__ = (
        # AC-01 стори 8.2: домен состояния — только `active`/`hidden`.
        CheckConstraint(_in_clause("status", CHAT_STATUSES), name="status"),
        # AC-01: публичный идентификатор уникален.
        UniqueConstraint("uuid", name="uq_chats_uuid"),
        # AC-01, ADR-04: инвариант «один чат на карточку» — на уровне БД.
        # Безусловный `UNIQUE`: у карточки либо есть чат, либо нет, а двух
        # активных чатов быть не может (состав компании один).
        UniqueConstraint("event_card_id", name="uq_chats_event_card_id"),
    )

    def __repr__(self) -> str:  # pragma: no cover - диагностика
        """Строка для логов: `uuid`, не внутренний `id` (D-2)."""
        return f"<Chat uuid={self.uuid} event_card_id={self.event_card_id}>"


__all__ = ["CHAT_STATUSES", "Chat"]
