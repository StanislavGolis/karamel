"""Модель обращения в поддержку `support_tickets` (стори 9.1; AC-01).

**Отдельная таблица, не JSONB-поле в `users`.** Обращение адресуется по API
(`GET /support/tickets` в 9.5, `POST /moderation/support/tickets/{uuid}/reply`
в 9.6), значит нужен собственный публичный ID и очередь с сортировкой —
оба невозможны внутри JSONB без индексов по элементам.

**`answered_by_id` — решение D-9.1-6.** Архитектура v1 этой колонки не знает,
но без неё спор «кто ответил» неразрешим вообще: `answer` и `answered_at`
описывают ЧТО и КОГДА, а не КТО. `ondelete='SET NULL'` — обращение остаётся
фактом при удалении учётки модератора (прецедент: `sanctions.moderator_id`).

**`subject` НЕ создаётся** (D-9.1-7). Архитектура §4.2 её упоминает, но ни один
AC эпика 9 не читает и не пишет её. Колонка «на будущее» — ложный контракт:
её заполнение никем не проверяется.

**`TimestampMixin` НЕ наследуется** (X-7.1-1). Путь записи ответа — сырой
`UPDATE ... SET status, answer, answered_at, answered_by_id`; `onupdate` ORM
на нём не срабатывает, и `updated_at` осталась бы старой навсегда — ложный
аудит «когда менялось».
"""

from __future__ import annotations

import uuid as uuid_lib
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    PrimaryKeyConstraint,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base
from app.models.enums import TICKET_STATUSES

#: AC-01: бикондиционал «статус ↔ ответ». Обе половины обязательны.
#:
#: Наивная форма `answer IS NULL OR answer IS NOT NULL` (или
#: `answered_at IS NULL OR answer IS NOT NULL`) — ДЕФЕКТ того же класса, что
#: `ck_notifications_read_order` до CR 7.3 H-2: при `answer IS NULL` выражение
#: даёт `UNKNOWN`, а `CHECK` отвергает только `FALSE`. Тогда `status='answered'`
#: без ответа проходил бы, и 9.5 показал бы пользователю «отвечено» с пустым
#: телом ответа. Бикондиционал перечисляет допустимые состояния явно.
ANSWER_PAIR_SQL = (
    "(status = 'open' AND answer IS NULL AND answered_at IS NULL) "
    "OR (status IN ('answered', 'closed') AND answer IS NOT NULL "
    " AND answered_at IS NOT NULL)"
)

#: AC-01, AC 9.5: пустое обращение запрещено СХЕМОЙ, не только `422`.
#:
#: **Почему не `length(btrim(body)) > 0`.** `btrim` без второго аргумента
#: снимает ТОЛЬКО пробел U+0020: `length(btrim(E'\t\n '))` возвращает `2`
#: (измерено на живой БД), то есть тело из табов прошло бы как «непустое».
#:
#: **Почему не `[^[:space:]]`.** Это была вторая, тоже неверная попытка
#: (CR 9.1 H-2). Класс `[:space:]` в PostgreSQL — это `[ \t\n\v\f\r]`
#: ПЛЮС символы, которые текущая **libc/locale** считает пробельными. При
#: `LC_CTYPE=C`/`POSIX` в класс НЕ входят NBSP U+00A0, NEL U+0085,
#: NNBSP U+202F и BOM U+FEFF — все четыре проходили как «непустые»
#: (измерено: `s ~ '[^[:space:]]'` = `t` для каждого). Хуже того, результат
#: зависел от локали БД: на стенде с `ru_RU.UTF-8` CHECK вёл бы себя иначе,
#: то есть ограничение было **непортируемым**.
#:
#: **Решение — явное перечисление Unicode-пробелов.** Регулярка не
#: обращается к локали вообще: она перечисляет кодпойнты, которые язык
#: считает пробельными (Zs-класс целиком + управляющие разделители).
#: Проверено на живой БД: все whitespace-only значения отвергаются, а
#: `U&'\00a0текст'` (NBSP + буквы) принимается.
BODY_NOT_BLANK_SQL = (
    "body ~ '[^[:space:]\u00a0\u0085\u1680\u2000-\u200b\u2028\u2029\u202f\u205f\u3000\ufeff]'"
)

#: AC-01: ответ не может быть раньше создания обращения.
ANSWER_ORDER_SQL = "answered_at >= created_at"


def _in_clause(column: str, values: tuple[str, ...]) -> str:
    """Собирает `CHECK (col IN ('a','b'))`. Копия — общий существующий долг."""
    return f"{column} IN ({', '.join(repr(str(v)) for v in values)})"


class SupportTicket(Base):
    """Обращение пользователя в поддержку и ответ модератора (FR55–FR57)."""

    __tablename__ = "support_tickets"

    # AC-01, P-10: `Identity()` = `GENERATED BY DEFAULT`, явная вставка `id = 0`
    # физически проходит — `CHECK (id > 0)` не декоративен (класс дефекта 6.7).
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)

    # AC-01: публичный адрес. `server_default` — потому что запись идёт сырым
    # `INSERT`, а не через ORM-дефолты; без него вставка падала бы.
    uuid: Mapped[uuid_lib.UUID] = mapped_column(
        PGUUID(as_uuid=True), nullable=False, server_default=text("gen_random_uuid()")
    )

    # AC-01: автор обращения. `CASCADE` — обращение без автора не адресуется
    # и не имеет смысла; удаление учётки уносит его обращения.
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )

    # AC-01: тело обращения. `Text`, не `String(N)`: обращение — свободный
    # текст, а лимит длины задаётся валидацией входа (9.5), не схемой.
    body: Mapped[str] = mapped_column(Text, nullable=False)

    # AC-01: жизненный цикл. `String(16)` с запасом: `answered` = 8.
    # D-3: `text + CHECK`, не PG-enum.
    status: Mapped[str] = mapped_column(String(16), nullable=False, server_default=text("'open'"))

    # AC-01: ответ модератора. `NULL` пока обращение открыто — это состояние
    # «ещё не отвечено», а не отсутствие данных.
    answer: Mapped[str | None] = mapped_column(Text, nullable=True)

    # AC-01: когда отвечено. Пара к `answer`, см. `ANSWER_PAIR_SQL`.
    answered_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # D-9.1-6: кто ответил. `SET NULL` — обращение переживает удаление учётки
    # модератора (прецедент: `sanctions.moderator_id`, ADR-07).
    answered_by_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )

    # AC-01, X-7.1-1: `created_at` ЯВНО, миксин не наследуется (`updated_at`
    # был бы мёртвой колонкой на сырых путях записи).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        PrimaryKeyConstraint("id"),
        # AC-01, P-10: защита от явной вставки неположительного id.
        CheckConstraint("id > 0", name="id_positive"),
        # AC-01: публичный адрес уникален.
        UniqueConstraint("uuid"),
        # AC-01: домен статуса.
        CheckConstraint(_in_clause("status", TICKET_STATUSES), name="status"),
        # AC-01, AC 9.5: пустое тело запрещено схемой.
        CheckConstraint(BODY_NOT_BLANK_SQL, name="body_not_blank"),
        # AC-01: статус и ответ согласованы (бикондиционал).
        CheckConstraint(ANSWER_PAIR_SQL, name="answer_pair"),
        # AC-01: ответ не раньше создания.
        CheckConstraint(ANSWER_ORDER_SQL, name="answer_order"),
        # 9.5: список своих обращений — `WHERE user_id = :u ORDER BY created_at
        # DESC`. `DESC` в составе: keyset по правилу D-9.
        Index("ix_support_tickets_user_created", "user_id", text("created_at DESC")),
        # 9.6: очередь модератора — `WHERE status = 'open' ORDER BY created_at`
        # («старые сверху»). Пара к предикату очереди, а не к списку своих.
        Index("ix_support_tickets_queue", "status", "created_at"),
    )


__all__ = [
    "ANSWER_ORDER_SQL",
    "ANSWER_PAIR_SQL",
    "BODY_NOT_BLANK_SQL",
    "SupportTicket",
]
