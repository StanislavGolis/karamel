"""Счётчик подряд идущих неудач health-probe (стори 10.7, AC-01, D-10.7-2).

**Почему Redis, а не память процесса.** `health-probe` живёт в контейнере с
`restart: unless-stopped`. Сценарий, ради которого существует алерт:
«база легла → probe отвечает неудачей → контейнер перезапустился → счётчик
в памяти снова 0 → алерт не уходит НИКОГДА». Счётчик обязан переживать
пересоздание процесса, поэтому он живёт в Redis — в том же хранилище, что
rate limiting и OAuth-state (ADR-14: новых таблиц не заводим).

**Почему не таблица в БД.** Наблюдать за базой через запись в базу нельзя:
когда база лежит, писать некуда. Это прямой довод ADR-14 (`:317`), а не
удобство.

**Почему `EXPIRE 86400`.** Предохранитель от вечно ненулевого счётчика:
если процесс умер между `INCR` и `DEL`, ключ со сроком истечёт сам. Без
срока такой остаток держал бы «1 неудачу» месяцами и при следующей
настоящей неудаче дал бы алерт на ПЕРВОМ отказе — защита от флейка
исчезла бы молча.
"""

from __future__ import annotations

from redis.asyncio import Redis

#: Ключ счётчика. Константа модуля, а не литерал на месте вызова: тест
#: (`test_health_state.py`) читает тот же ключ, и расхождение в строке
#: сделало бы проверку переживания пересоздания тавтологией.
FAILURES_KEY = "health:failures:consecutive"

#: Срок жизни ключа, секунды (сутки). См. довод в модульном докстринге.
FAILURES_TTL_SECONDS = 86_400


async def register_failure(redis: Redis) -> int:
    """Увеличивает счётчик неудач и возвращает новое значение.

    `INCR` + `EXPIRE` двумя командами, а не `INCR` с опцией: `INCR` не имеет
    формы с TTL, а конвейер (`pipeline`) скрыл бы ошибку соединения до
    `execute`. Две команды подряд — цена одной лишней RTT раз в минуту.

    `RedisError` здесь НЕ глотается: вызывающий (`health_probe.run_once`)
    обязан отличить «счётчик не растёт» (Redis лёг — алерт немедленно,
    D-10.7-3) от «неудача зарегистрирована».
    """
    value = await redis.incr(FAILURES_KEY)
    await redis.expire(FAILURES_KEY, FAILURES_TTL_SECONDS)
    return int(value)


async def register_success(redis: Redis) -> None:
    """Сбрасывает счётчик: успех разрывает серию (AC-01).

    `DEL`, а не `SET 0`: ноль — это значение счётчика, а не его отсутствие;
    сброс через `SET 0` оставил бы ключ жить сутки и делал бы `KEYS health:*`
    в диагностике шумным. `RedisError` не глотается — по той же причине,
    что и в `register_failure`.
    """
    await redis.delete(FAILURES_KEY)
