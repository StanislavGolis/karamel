"""Нормализация полей анкеты (Task 3.1–3.4; AC-04).

Почему это отдельный модуль, а не методы сервиса: нормализация — чистая
функция без БД, сессии и настроек (эталон города приходит аргументом).
Чистую функцию можно покрыть таблицей «вход → выход» и переиспользовать
в воркере или миграции данных, не поднимая сессию.

D-5 стори 2.3: канонизация города живёт здесь, а не в БД. CHECK в БД
умеет только края (`btrim`) и пустоту; `CHECK (lower(city) = city)` заставил
бы хранить «томск», а показывать нужно «Томск».

Ключевой дефект, который закрывает модуль: `'Томск'`, `'томск'`,
`'Томск\\u00a0'` и `'Томск\\t'` — четыре разные строки для PostgreSQL.
Выборка `WHERE city = 'Томск'` (2.6) нашла бы только первую, а `btrim`
не режет NBSP и таб — то есть CHECK их пропускает.
"""

from __future__ import annotations

import re
import unicodedata

# NBSP (U+00A0) и узкий неразрывный пробел (U+202F) — типографские пробелы,
# которые приходят из копипаста, iOS-автозамены и вёрстки. Для PostgreSQL это
# обычные символы: `btrim` их не режет, `lower()` их не трогает.
_NBSP = "\u00a0"
_THIN_NBSP = "\u202f"

# Горизонтальные пробельные символы. Перевод строки (`\\n`) сюда НЕ входит:
# в тексте анкеты он разделяет абзацы и является смыслом, а не шумом.
_HORIZONTAL_WS = re.compile(r"[ \t\f\v\r]+")
# Любой пробельный символ, включая переводы строк: для однострочных полей
# (имя, город) перенос строки — это тот же шум, что двойной пробел.
_ANY_WS = re.compile(r"\s+")


def _strip_invisible(value: str, *, keep_newlines: bool) -> str:
    """CR 2.3, патчи 2–3: удаляет NUL, управляющие и форматирующие символы.

    `\\x00` (NUL) — не пробел и не снимается `strip()`: PostgreSQL отвергает
    его в `text`/`varchar` с `CharacterNotInRepertoireError`, и пользователь
    получал `500` на копипасте из PDF или вставке из мессенджера.

    ZWSP (`U+200B`), BOM (`U+FEFF`), `\\u0001`, `\\u001b` относятся к категориям
    Unicode `Cf` (формат) и `Cc` (управляющие). Они не матчатся `\\s`,
    `strip()` их не снимает, а CHECK в БД их пропускает: «город» из одного
    ZWSP выглядел бы непустым и навсегда выпал из выборки по городу.

    `keep_newlines=True` — для `bio`: `\\n` там разделяет абзацы и является
    смыслом, а не шумом. `\\t` удаляется всегда: после схлопывания пробелов
    он и так стал бы пробелом.
    """
    return "".join(
        char
        for char in value
        # Пробельные символы не удаляются: их судьбу решает следующий шаг
        # (схлопывание). Удалить таб значило бы склеить слова — хуже, чем
        # оставить лишний пробел.
        if not (unicodedata.category(char) in {"Cf", "Cc"} and not char.isspace())
    )


def _replace_typographic_spaces(value: str) -> str:
    """NBSP и тонкий пробел → обычный пробел.

    Отдельная функция, потому что замену должны делать ВСЕ поля: NBSP
    в имени даёт «Аня\\u00a0М», которое не находится поиском по «Аня М».
    """
    return value.replace(_NBSP, " ").replace(_THIN_NBSP, " ")


def normalize_text(value: str) -> str:
    """Task 3.1 (AC-04): базовая нормализация однострочного значения.

    Порядок шагов важен:
    1. NFC — «й» в разложенной форме (macOS) приводится к одной кодовой точке.
       Без этого визуально одинаковые строки не равны побайтово.
    2. NBSP/тонкий пробел → обычный пробел — иначе `btrim` в БД их не срежет.
    3. Любые пробельные последовательности (включая `\\n`) → один пробел:
       для города и имени перенос строки — такой же шум, как двойной пробел.
    4. `strip()` — края без пробелов, как требует CHECK `city = btrim(city)`.

    Возвращает пустую строку для пустого/пробельного ввода: решение
    «это ошибка `*_required`» принимает сервис, а не нормализация.
    """
    cleaned = _strip_invisible(value, keep_newlines=False)
    normalized = unicodedata.normalize("NFC", _replace_typographic_spaces(cleaned))
    collapsed = _ANY_WS.sub(" ", normalized)
    return collapsed.strip()


# Малые частицы составных названий: после дефиса или пробела они пишутся
# со строчной ('Ростов-на-Дону', а не 'Ростов-На-Дону'). Список закрытый
# и объясняет единственное расхождение между двумя русскими правилами:
# «все части с заглавной» (Санкт-Петербург) и «служебное слово строчное».
# Без него пришлось бы выбрать одно правило и испортить другую половину
# названий — `str.title()` делает именно это.
_CITY_PARTICLES = frozenset(
    {"на", "под", "у", "в", "за", "при", "по", "де", "дер", "ван", "фон", "ла", "ди", "да"}
)


def _capitalize_word(word: str) -> str:
    """Заглавная первая буква, остальные строчные: `'ТОМСК'` → `'Томск'`.

    `str.capitalize()` для этой роли не годится: он опускает остаток слова,
    но в составном названии («санкт-петербург») применялся бы к целой строке
    и дал бы «Санкт-петербург».
    """
    if not word:
        return word
    return word[0].upper() + word[1:].lower()


def _capitalize_city_part(word: str, *, first: bool) -> str:
    """Часть названия: частица — строчными, всё остальное — с заглавной.

    `first` отличает `'Ростов'` (первая часть, всегда с заглавной) от
    `'на'` посередине. Проверка идёт по `casefold()`, а после первого
    прохода регистр части может быть любым (`'НА'`, `'На'`).
    """
    if not word:
        return word
    if not first and word.casefold() in _CITY_PARTICLES:
        return word.lower()
    return _capitalize_word(word)


def normalize_city(value: str, pilot_city: str) -> str:
    """Task 3.2 (AC-04, D-5, FR16): канонизация города.

    Порядок:
    1. Нормализация текста (NFC, NBSP, пробелы, края).
    2. Если `casefold()` совпал с городом пилота — вернуть написание
       из `pilot_city` дословно. Это единственный способ гарантировать,
       что `'томск'` и `'Томск'` сведутся к одному значению, которое
       использует выборка 2.6; эталон берётся из конфига (FR16), а не
       из литерала в коде.
    3. Иначе — заглавная в каждом слове. Слова разделены пробелом
       и дефисом: `'ростов-на-дону'` → `'Ростов-на-Дону'`.

    `str.title()` запрещён (анти-паттерн стори): он даёт `'Ростов-На-Дону'`
    с заглавной после дефиса, и пользователь увидит «Санкт-Петербург»
    в одном написании, а «Ростов-На-Дону» — в другом.

    Пустой ввод возвращает пустую строку: доменный код `city_required`
    выставляет сервис, чтобы один и тот же ввод не давал разные ошибки
    в зависимости от точки вызова.
    """
    normalized = normalize_text(value)
    if not normalized:
        return ""
    # CR 2.3, патч 4: возвращается НОРМАЛИЗОВАННЫЙ эталон, а не сырой аргумент.
    # `PILOT_CITY="  Томск  "` (пробел в `.env` — обычное дело) иначе вернул бы
    # строку с пробелами по краям: CHECK `city = btrim(city)` дал бы
    # `IntegrityError` → `500` на валидном вводе.
    canonical = normalize_text(pilot_city)
    if canonical and normalized.casefold() == canonical.casefold():
        return canonical
    words = normalized.split(" ")
    capitalized: list[str] = []
    for word in words:
        parts = word.split("-")
        # Первая часть первого слова — всегда с заглавной; частицы (`на`, `под`)
        # строчные только внутри названия, поэтому `first` считается по позиции
        # в целом городе, а не в слове.
        capitalized.append(
            "-".join(
                _capitalize_city_part(part, first=(index == 0 and not capitalized))
                for index, part in enumerate(parts)
            )
        )
    return " ".join(capitalized)


def normalize_name(value: str) -> str:
    """Task 3.3 (AC-04): имя — нормализация без изменения регистра.

    Регистр имени — решение пользователя: автокапитализация испортила бы
    ники и составные имена («ван дер Саар» → «Ван Дер Саар»).
    """
    return normalize_text(value)


def normalize_bio(value: str) -> str:
    """Task 3.4 (AC-04): текст анкеты — пробелы схлопываются, абзацы нет.

    Отличие от `normalize_text`: перевод строки — часть смысла (шесть-семь
    строк текста, UX). Схлопываются только горизонтальные пробелы: таб,
    двойной пробел из копипаста, `\\r` из Windows-формы.

    Пробел перед переводом строки убирается (иначе в БД лежит «горы \\n»),
    а пробел после него — нет: отступ в начале строки пользователь поставил
    осознанно, и `btrim` его не тронет, потому что край строки — не это место.
    """
    cleaned = _strip_invisible(value, keep_newlines=True)
    normalized = unicodedata.normalize("NFC", _replace_typographic_spaces(cleaned))
    collapsed = _HORIZONTAL_WS.sub(" ", normalized)
    # Пробел перед переводом строки — шум: «горы \\n» и «горы\\n» неотличимы
    # для читателя, но различаются в БД.
    collapsed = collapsed.replace(" \n", "\n")
    return collapsed.strip()
