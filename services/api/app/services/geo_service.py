"""Определение города по координатам (Task 7.1–7.2; AC-06, FR12, FR59).

D-9: внешний геокодер НЕ вызывается. Передача координат в сторонний сервис —
трансграничная передача ПД (NFR34, 152-ФЗ), а в пилоте город один: сравнения
с прямоугольником `PILOT_CITY_BBOX` достаточно, и оно не покидает процесс.

D-9: координаты не логируются и не сохраняются. Они живут в теле одного
запроса: валидация диапазонов → сравнение с прямоугольником → ответ только
названием города. Базы, кэша и журналов с `lat`/`lng` нет — тест
`test_coordinates_are_not_logged` фиксирует это как контракт, а не как
пожелание.

Функция чистая: прямоугольник и город приходят аргументами, а не читаются
из `settings` внутри. Иначе unit-тест зависел бы от `.env` разработчика,
а переиспользование с другим пилотом потребовало бы правки модуля.
"""

from __future__ import annotations


def locate_city(
    *,
    lat: float,
    lng: float,
    bbox: tuple[float, float, float, float],
    pilot_city: str,
) -> str | None:
    """AC-06: город пилота, если точка внутри прямоугольника, иначе `None`.

    `bbox` — `(lat_min, lat_max, lng_min, lng_max)` (порядок проверяется
    валидатором конфига, Task 1.2). Границы включены с обеих сторон: житель
    на краю прямоугольника — всё ещё житель пилота, и исключение границы
    давало бы «город не определился» на верной геолокации.

    `None` — не ошибка: точка вне пилота нормальна (гость из другого города).
    Роутер превращает её в `{"city": null, "reason": "outside_pilot_city"}`,
    чтобы клиент показал «введите город вручную», а не техническую ошибку.

    Координаты в лог не попадают (D-9): ни `info`, ни `debug`. Значение
    `lat`/`lng` — ПД по FR59, и журнал контейнера хранится дольше БД.
    """
    lat_min, lat_max, lng_min, lng_max = bbox

    if not (lat_min <= lat <= lat_max):
        return None
    if not (lng_min <= lng <= lng_max):
        return None
    return pilot_city
