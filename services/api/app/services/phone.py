"""Нормализация номера телефона (Task 2, AC-05).

Функция чистая: без БД, Redis и настроек. Одна точка нормализации вызывается
и в `/request`, и в `/verify`: если бы каждый роут нормализовал сам, код,
выданный на `8 900 …`, не нашёлся бы при проверке `+7 900 …`, и пользователь
получал бы `code_expired` на верном коде.

Принимаются только российские номера: пилот в Томске, провайдер РФ (SMS.ru).
Международный номер ушёл бы как дорогое сообщение и не дошёл бы до адресата.
"""

from __future__ import annotations

import re

# AC-05: убираются ровно те разделители, которые встречаются в вводе с экрана:
# пробелы (включая неразрывный), дефисы (включая типографский), скобки, точки.
_SEPARATORS = re.compile(r"[\s\-\u2010-\u2015().]+")
# AC-05: ровно 11 цифр, первая 7 (или 8 в национальной записи). Паттерн с
# квантификатором, а не `\d` + `len()`: `fullmatch(r"\d")` требует строку из
# одной цифры и отвергал бы любой настоящий номер.
_DIGITS_TOTAL = 11
# re.ASCII обязателен: `\d` в Python матчит юникодные цифры (арабо-индийские ٩٠٠،
# полноширинные ９００). Без флага '+7٩٠٠١٢٣٤٥٦٧' проходил валидацию как отдельный
# номер: один физический телефон получал второй аккаунт, а per-phone лимит
# и HMAC-привязка разъезжались по разным строкам.
_DIGITS = re.compile(rf"[0-9]{{{_DIGITS_TOTAL}}}")


class InvalidPhoneError(Exception):
    """Номер не приводится к российскому E.164.

    Отдельное исключение, а не `ValueError`: роут обязан отличить «клиент
    прислал мусор» (400 `invalid_phone`) от внутренней ошибки (500), а
    `ValueError` ловится слишком широко — в него падают и баги сериализации.
    """


def normalize_phone(raw: str) -> str:
    """Task 2.1–2.2 (AC-05): приводит номер к `+7XXXXXXXXXX`.

    `+79001234567`, `89001234567`, `79001234567` и любые их записи с пробелами,
    дефисами, скобками и точками дают одно значение. Всё остальное —
    `InvalidPhoneError`: буквы, пустая строка, 9 или 12 цифр, чужие коды стран.
    """
    if not isinstance(raw, str):
        raise InvalidPhoneError("номер должен быть строкой")
    cleaned = _SEPARATORS.sub("", raw.strip())
    if not cleaned:
        raise InvalidPhoneError("пустой номер")
    # AC-05: `+` допустим только ведущим. Внутри номера он означал бы склейку
    # двух номеров в один (`+7900+1234567`), и проверка цифр её пропустила бы.
    body = cleaned[1:] if cleaned.startswith("+") else cleaned
    if not _DIGITS.fullmatch(body) or len(body) != _DIGITS_TOTAL:
        raise InvalidPhoneError("номер не приводится к 11 цифрам")
    # AC-05: 8 — национальный префикс, 7 — код страны. Остальное (1, 380, …) —
    # не наш номер: подтверждение владения таким номером ничего не даёт продукту.
    if body[0] == "8":
        body = "7" + body[1:]
    elif body[0] != "7":
        raise InvalidPhoneError("только российские номера")

    # Только мобильные: после кода страны идёт код оператора, начинающийся с 9.
    # 8-800-555-35-35 и городские 8-495-… формально 11 цифр, но SMS.ru их либо
    # не доставит, либо спишет по другому тарифу — пользователь получил бы 200
    # и потом `code_expired` на верном коде.
    if body[1] != "9":
        raise InvalidPhoneError("только мобильные номера")

    return "+" + body
