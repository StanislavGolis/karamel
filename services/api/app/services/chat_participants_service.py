"""Состав компании (стори 6.3; AC-01…AC-05).

Экран отвечает на вопрос «с кем и куда я иду»: карточка события + профили
всех участников компании. Состав НЕ хранится (ADR-04): он вычисляется из
`join_requests.status='selected'`, а автор добавляется из карточки — иначе
денормализованный список разошёлся бы с заявками при отмене участия (5а.6)
и при замене выбранного (5б.3).

**Гард доступа переиспользуется, а не дублируется** (требование стори).
`get_card` (4.5/5б.2) уже отвечает на вопрос «видит ли зритель карточку» и
считает `viewer_participates` — признак «зритель в составе компании»
(D-5b.2-7). Второй предикат `selected` здесь разошёлся бы с ним при первом
же добавлении статуса, поэтому состав строится поверх готового `CardFeedItem`.

**Почему один класс ошибки** (D-6.3-1). «Карточки нет», «чужая община»,
«не участник» и «участник с `pending`-заявкой» дают ОДИН ответ: `404` с
тем же телом. Разные классы с одинаковым статусом разошлись бы при первой
правке `details`, и анти-оракул (ADR-13, NFR33) сломался бы молча.

**NFR7.** Число запросов не зависит от размера компании: карточка (с
признаком участия) — `get_card`, участники — один запрос, фото — пачка.
Построчная подпись фото дала бы 6 запросов на компанию из шести человек.
"""

from __future__ import annotations

import uuid as uuid_lib
from dataclasses import dataclass
from typing import Protocol

import structlog
from sqlalchemy.ext.asyncio import AsyncSession

from app.repositories.chats import ChatRepository
from app.repositories.profile_photos import ProfilePhotoRepository
from app.services.event_card_service import (
    CardFeedItem,
    CardNotFoundError,
    CardSettings,
    get_card,
)
from app.services.media_service import MediaStorageError, MediaUnavailableError, get_signed_url

logger = structlog.get_logger(__name__)

# CR 6.3, F-1 (AC-02, ADR-13): заведомо несуществующий `card_id` для
# выравнивания числа запросов на пути «карточки нет». `event_cards.id` —
# `GENERATED BY DEFAULT AS IDENTITY`, начинается с 1, поэтому 0 не совпадёт
# ни с одной строкой никогда — не «магическое число», а гарантия пустоты.
# Отдельная константа, а не литерал на месте вызова: смысл значения иначе
# не читается, и следующий читатель «починит» его на `-1` или `None`.
_MISSING_CARD_ID = 0


class ParticipantsSettings(CardSettings, Protocol):
    """Минимум настроек: `CardSettings` (нужен `get_card`) плюс TTL подписи фото.

    Наследование от `CardSettings`, а не второй независимый протокол: состав
    вызывает `get_card`, и структурная несовместимость нашлась бы только
    mypy-ошибкой на месте вызова, а не при объявлении. Расширение — только
    добавление поля, существующий минимум не переписывается.

    TTL объявлен здесь, а не прочитан `getattr`: опечатка в имени поля молча
    подменилась бы дефолтом, и срок жизни ссылки разошёлся бы с остальными
    фото-контрактами.
    """

    s3_signed_url_ttl: int


class ParticipantsNotFoundError(Exception):
    """AC-02 (ADR-13, D-6.3-1): состав недоступен — ответ неотличим от «нет карточки».

    Класс ОДИН на четыре случая: нет карточки, чужая община, не участник,
    участник с `pending`-заявкой. Тело ответа одно (`card_not_found`), и
    `403` здесь был бы утечкой существования (ADR-13).
    """

    code = "card_not_found"


@dataclass(frozen=True)
class CompanyMember:
    """AC-01, AC-03: один участник компании — доменный объект, не схема.

    `user_uuid` — публичный идентификатор (D-2): внутренний `id` живёт
    только в репозитории и нужен лишь для пакетной подписи фото.

    `is_author` — признак АВТОРА карточки, а не «первого в списке»: порядок
    и признак связаны, но не тождественны, и вычислять одно из другого
    значит связать два правила.

    `name`/`age` — `None`, если анкеты нет (онбординг не пройден): участник
    остаётся в составе, он часть компании.
    """

    user_uuid: uuid_lib.UUID
    name: str | None
    age: int | None
    is_author: bool
    photo_url: str | None
    photo_expires_in: int | None


@dataclass(frozen=True)
class CardParticipants:
    """AC-01: ответ экрана — карточка события и состав компании.

    `card` — тот же `CardFeedItem`, из которого роутер собирает
    `EventCardRead` (`_card_to_read`, D-6.3-4): отдельная «краткая карточка
    для состава» разошлась бы с лентой при первом добавлении поля.
    """

    card: CardFeedItem
    items: list[CompanyMember]


async def list_card_participants(
    session: AsyncSession,
    *,
    viewer_id: int,
    card_uuid: uuid_lib.UUID,
    viewer_community_slug: str,
    settings: ParticipantsSettings,
) -> CardParticipants:
    """AC-01…AC-05: состав компании для её участника.

    Порядок шагов — контракт, каждый следующий опирается на предыдущий:

    1. карточка через `get_card` (4.5): срез сообщества, `draft` чужого
       автора → `CardNotFoundError`, ленивое закрытие окна и вычисленный
       `viewer_participates`. Второй запрос видимости не заводится;
    2. `CardNotFoundError` → `ParticipantsNotFoundError`: ИМЕННО тот же
       класс, что у «не участник», иначе тела разойдутся (D-6.3-1);
    3. участие: автор карточки ИЛИ `viewer_participates`. Автор — участник
       по определению (ADR-04), у него нет строки в `join_requests`, и
       `viewer_participates` для него всегда `false`;
    4. не участник → `404` — до всякой выборки состава (посторонний не
       должен даже косвенно узнать число людей);
    5. участники — ОДНИМ запросом (`ChatRepository.list_participants`);
    6. фото — ПАЧКОЙ по автору и всем участникам сразу;
    7. сборка: автор первым (D-6.3-3), затем участники в порядке
       присоединения.

    Запись НЕ выполняется, кроме ленивых переходов самой карточки
    (`get_card` коммитит только при фактической мутации, CR 4.5): состав —
    чтение (§18.3 — гонок здесь нет).
    """
    try:
        card = await get_card(
            session,
            card_uuid=card_uuid,
            viewer_id=viewer_id,
            # AC-05 стори 10.1: срез сообщества — колонка зрителя, не конфиг.
            # Здесь зритель — участник/заявитель карточки, его слаг уже прочитан
            # выше по коду (тот же пользователь, что и `viewer_id`).
            viewer_community_slug=viewer_community_slug,
            settings=settings,
        )
    except CardNotFoundError as error:
        # AC-02, D-6.3-1: «нет карточки» и «не участник» — один класс и одно тело.
        #
        # CR 6.3, находка F-1 (AC-02, ADR-13, NFR33): ТАЙМИНГ-ОРАКУЛ.
        # `get_card` считает `viewer_participates` ТОЛЬКО когда карточка
        # найдена, поэтому на существующую карточку уходило 3 SQL-запроса, а
        # на несуществующую — 2. Тело и заголовки совпадали, но посторонний
        # отличал существование по времени ответа — та же утечка, что `403`.
        #
        # Выравнивание: на этом пути выполняется ТОТ ЖЕ запрос состава с
        # заведомо несуществующим `card_id` (`_MISSING_CARD_ID`). Стоимость
        # одного обращения к БД совпадает с `viewer_participation_card_ids`
        # найденной карточки, результат заведомо пуст и не проверяется:
        # задача — не дать времени ответа зависеть от существования карточки.
        await ChatRepository(session).list_participants(
            card_id=_MISSING_CARD_ID,
            community_slug=settings.default_community_slug,
        )
        raise ParticipantsNotFoundError() from error

    is_author = card.card.author_id == viewer_id
    # AC-02: состав видят ТОЛЬКО члены компании. `viewer_participates` —
    # готовый признак 5б.2 (D-5b.2-7); второй предикат `selected` здесь
    # разошёлся бы с ним при добавлении статуса.
    if not is_author and not card.viewer_participates:
        raise ParticipantsNotFoundError()

    rows = await ChatRepository(session).list_participants(
        card_id=card.card.id,
        community_slug=settings.default_community_slug,
    )

    # AC-05 (NFR7): фото — ОДИН запрос на автора и всех участников.
    user_ids = [card.card.author_id, *(row[0] for row in rows)]
    storage_keys = await ProfilePhotoRepository(session).list_primary_approved_by_user_ids(user_ids)
    signed = _sign_photos(storage_keys, settings)
    ttl = settings.s3_signed_url_ttl

    items: list[CompanyMember] = [
        CompanyMember(
            user_uuid=card.author_uuid,
            name=card.author_name,
            age=card.author_age,
            is_author=True,
            photo_url=signed.get(card.card.author_id),
            # AC-01, D-5a.4-6: TTL есть только вместе со ссылкой — одно поле
            # вместо пары «флаг + срок», которая могла бы противоречить себе.
            photo_expires_in=ttl if card.card.author_id in signed else None,
        )
    ]
    items.extend(
        CompanyMember(
            user_uuid=user_uuid,
            name=name,
            age=age,
            is_author=False,
            photo_url=signed.get(user_id),
            photo_expires_in=ttl if user_id in signed else None,
        )
        for user_id, user_uuid, name, age, _submitted_at in rows
    )

    logger.info(
        "card_participants.listed",
        card_uuid=str(card_uuid),
        size=len(items),
    )
    return CardParticipants(card=card, items=items)


def _sign_photos(storage_keys: dict[int, str], settings: ParticipantsSettings) -> dict[int, str]:
    """AC-01, D-11: подписать главные фото участников, сбой — не ошибка.

    Приём `_sign_applicant_photos` (5а.4) с СВОИМ именем события
    (`card_participants.photo.sign_failed`): чужое имя сделало бы экраны
    неразличимыми в логах.

    Подпись локальная (`generate_presigned_url` не ходит в сеть), поэтому
    вызов синхронный. Сбой хранилища НЕ валит состав: `PersonMini` покажет
    инициалы, а `500` на весь экран из-за одного отсутствующего объекта в
    бакете — несоразмерно.

    `MediaUnavailableError` ловится ВМЕСТЕ с `MediaStorageError` явно: он не
    их наследник, и без этой ветки он уходил бы в общий обработчик → `500`
    (долг CR 5а.3 — не повторять).

    URL не логируется никогда (D-11): в лог идёт только факт сбоя.
    """
    signed: dict[int, str] = {}
    ttl = settings.s3_signed_url_ttl
    for user_id, storage_key in storage_keys.items():
        try:
            signed[user_id] = get_signed_url(storage_key, ttl=ttl)
        except (MediaStorageError, MediaUnavailableError):
            logger.warning("card_participants.photo.sign_failed", user_id=user_id)
    return signed
