/**
 * Публичный маршрут мониторинга `GET /api/health` (стори 11.2, AC-1, AC-3.2, AC-4.1).
 *
 * **Зачем маршрут существует.** Внешний uptime-монитор (UptimeRobot) —
 * единственное исключение из `NFR65`, разрешённое решением владельца Р2
 * от 2026-10-27 (см. оговорку к `NFR65` в `prd-v2-action-first.md:858-866`).
 * Монитор обязан опрашивать публичный `GET` без авторизации и без данных.
 * Такого маршрута не существовало: `/health` живёт только у api и опубликован
 * на `127.0.0.1:8000` (`docker-compose.yml:35`), снаружи недоступен.
 *
 * **Почему тонкий прокси, а не что-то ещё.**
 * - api наружу не публикуется: расширять поверхность атаки ради одной
 *   проверки — нарушение духа NFR65 «одно исключение, минимальный след»;
 * - `/api/proxy/*` для монитора непригоден: он ходит в `/api/v1/*`, тянет
 *   cookie сессии и обновляет её — монитор получил бы 401, а в запрос
 *   попали бы cookie (прямое нарушение AC-3).
 *
 * **Почему не проверяет БД.** AC-4 и контракт стори 1.1
 * (`services/api/tests/unit/test_health.py`) запрещают внешние вызовы в
 * health. Публичный маршрут повторяет тот же смысл: «процесс web отвечает и
 * видит api», а не «всё в порядке». Проверка БД — задача `/health/deep` и
 * probe, а не монитора, который не имеет права писать в нашу БД (AC-4).
 *
 * **Чего маршрут не делает и не должен начать делать:**
 * - не раздаёт `Set-Cookie` и не переиспользует сессию;
 * - не отдаёт `version`, `host`, `uptime`, имена сервисов — тело ровно
 *   `{"status":"ok"}` / `{"status":"unavailable"}`;
 * - не кэшируется: кэшированный health не замечает падения, то есть
 *   тавтологичен (правило 18.2);
 * - не следует редиректам api (см. `redirect: "manual"` ниже).
 */

/**
 * AC-3: `API_URL` читается в момент запроса, а не на этапе сборки.
 *
 * Та же причина, что в `api/proxy/[...path]/route.ts:37-39`: значение в образе
 * меняют без пересборки, а прочитанное на верхнем уровне зашилось бы в бандл
 * при `next build`.
 *
 * **Возвращает `null`, если адрес не задан или пуст (CR-находка N-4).**
 * Прежний дефолт `http://127.0.0.1:8000` внутри контейнера web указывает на
 * сам web: api слушает 8000 в своём контейнере, а не в web. Монитор краснел бы
 * навсегда без следа причины. Теперь отсутствие `API_URL` — явная
 * недоступность с записью в лог, а не тихий поход на себя.
 * Причина, по которой это не ломает стенд: `docker-compose.yml:180` задаёт
 * `API_URL: ${API_URL:-http://api:8000}` — переменная есть всегда.
 */
function apiUrl(): string | null {
  const raw = process.env.API_URL;
  if (raw === undefined) return null;
  const trimmed = raw.trim();
  if (trimmed === "") return null;
  // CR-находка N-1/4: без этой нормализации `API_URL=http://api:8000/` даёт
  // `//health`, который api не обслуживает.
  return trimmed.replace(/\/+$/, "");
}

// D-11.2-3: сегментные опции здесь НЕ объявляются — `next.config.ts` включает
// `cacheComponents`, и Next 16 отклоняет их все
// (`Route segment config "dynamic" is not compatible with nextConfig.cacheComponents`
// и то же для `runtime`). Сборка падала на обеих.
//
// Почему это не делает маршрут кэшируемым: при `cacheComponents` GET-route
// handlers по умолчанию **динамические** — кэш включается только явной
// директивой `"use cache"` или `cache: "force-cache"` в `fetch`. Ни того, ни
// другого здесь нет, и `cache: "no-store"` в вызове ниже фиксирует это
// намерение явно. Обратный гард — тест W-11.2-T5.

/** Таймаут проверки: монитор ждёт ответа не дольше своего интервала. */
const HEALTH_TIMEOUT_MS = 5_000;

/** Единая форма ответа: ровно один ключ, без внутренностей стенда. */
function reply(status: number, body: "ok" | "unavailable"): Response {
  return Response.json(
    { status: body },
    { status, headers: { "cache-control": "no-store" } },
  );
}

/**
 * CR-находка N-3: тело ответа upstream не дочитывается.
 *
 * На каждый опрос (288/сутки) оставался занятый сокет в пуле. `cancel()`
 * закрывает поток, не читая его: содержимое health нам не нужно ни в одной
 * ветви. Ошибку глушим: сокет мог быть уже закрыт, и падать из-за этого
 * health не имеет права.
 */
async function discardBody(response: Response): Promise<void> {
  try {
    await response.body?.cancel();
  } catch {
    // Тело уже закрыто — для нас это успех, а не ошибка.
  }
}

/** Причина недоступности — в лог: без неё 503 неотличим от «сломалось что-то ещё». */
function warn(reason: string): void {
  console.warn(`[api/health] ${reason}`);
}

/**
 * AC-1 / AC-3.2 / D-11.2-2: 200 при живом api, **503** при любом другом исходе.
 *
 * Монитор судит по HTTP-коду, а не по телу: «200 с `status: degraded`» — это
 * вечный зелёный (ключевое слово-мониторинг на бесплатном тарифе недоступен).
 * Поэтому не-2xx, редирект, отказ соединения и таймаут одинаково дают 503.
 *
 * В запросе к api нет ни `Authorization`, ни `Cookie`, ни `X-*` (AC-3):
 * маршрут не переиспользует сессию и не передаёт ничего от клиента.
 */
export async function GET(): Promise<Response> {
  const base = apiUrl();
  if (base === null) {
    // AC-1: нет адреса — api недоступен по определению, а не «настроен криво».
    warn("API_URL не задан или пуст — api недоступен");
    return reply(503, "unavailable");
  }

  try {
    const response = await fetch(`${base}/health`, {
      method: "GET",
      cache: "no-store",
      // AC-1 / CR-находка N-2: `fetch` по умолчанию следует редиректам, поэтому
      // captive-portal или `http→https` редирект (302/308) при мёртвом api
      // зеленил монитор: 302 → переход → 200. С `manual` редирект остаётся
      // редиректом, `response.ok` для него `false`, и монитор краснеет.
      redirect: "manual",
      signal: AbortSignal.timeout(HEALTH_TIMEOUT_MS),
    });

    // AC-1: тело upstream намеренно не переиспользуется — контракт публичного
    // маршрута ровно один ключ. Не читаем, но и не бросаем незакрытым (N-3).
    await discardBody(response);

    if (response.ok) {
      return reply(200, "ok");
    }

    // AC-1: 3xx/4xx/5xx и любой не-2xx — api ответил не тем, что должен.
    warn(`api ответил ${response.status} — недоступность`);
  } catch (error) {
    // AC-1: отказ соединения и таймаут — недоступность, а не 500 из недр Next.
    warn(`запрос к api не удался: ${error instanceof Error ? error.message : String(error)}`);
  }

  return reply(503, "unavailable");
}
