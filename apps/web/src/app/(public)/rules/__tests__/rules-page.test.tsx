/**
 * Тесты публичной страницы правил (стори 10.4; AC-01, AC-02).
 *
 * **Почему рендер, а не только чтение файла.** `redirect()` в серверном
 * компоненте не возвращает значение, а бросает исключение `NEXT_REDIRECT`.
 * Значит страница, которая кого-то выгоняет, не отрендерится — тест получит
 * исключение вместо HTML (AC-01.2). Это проверка поведения, а не текста.
 *
 * **Почему ещё и чтение исходника.** Рендер не видит две вещи: (1) проверку
 * сессии, которая в jsdom тихо возвращает `null` вместо сессии и не бросает;
 * (2) редирект внутри общего компонента, вызванного из страницы. Статический
 * гард читает `page.tsx` и падает на запрещённых конструкциях (AC-01.1).
 *
 * **Почему фильтры по классам, а не по цвету пикселя.** jsdom не считает
 * контраст. Гейт 5 проверяет литеральные цвета в исходниках и пары «фон ×
 * текст» — здесь проверяется, что на странице вообще нет литералов и
 * анимаций (AC-02.5, AC-02.7), а числа контраста — за гейтами 2–5.
 */

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";

import RulesPage, { metadata } from "@/app/(public)/rules/page";
import { MODERATION_RULES_SECTIONS } from "@/lib/moderation-rules";

/** Каталог этого теста: путь к `page.tsx` строится от него, не от cwd. */
const TEST_DIR = dirname(fileURLToPath(import.meta.url));
const PAGE_PATH = join(TEST_DIR, "..", "page.tsx");

/** Исходник страницы как текст. */
const PAGE_SOURCE = readFileSync(PAGE_PATH, "utf8");

/**
 * Исходник без комментариев.
 *
 * Комментарии в этом проекте объясняют запреты и потому содержат слова
 * `redirect(`, `cookies(` буквально. Гард по «сырому» тексту краснел бы на
 * собственных пояснениях — то есть на документации правила, а не на его
 * нарушении.
 */
const PAGE_CODE = PAGE_SOURCE.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

/**
 * HTML страницы, отрендеренный без единого запроса и без сессии.
 *
 * **Почему функция, а не константа модуля** (P-1 код-ревью 10.4):
 * `redirect()` в серверном компоненте бросает `NEXT_REDIRECT` во время
 * рендера. На верхнем уровне модуля это исключение всплывает на этапе
 * **сбора файла** — vitest печатает `Tests no tests`, ни один `it()` не
 * регистрируется, и статический гард AC-01.1 не выполняется. Красный прогон
 * в таком случае ничего не доказывает про гард (P-21: «красный тест ≠
 * сработавшая проверка»).
 *
 * Внутри `it()` исключение становится падением **этого** теста, остальные
 * тесты файла собираются и выполняются.
 */
function pageHtml(): string {
  return renderToStaticMarkup(<RulesPage />);
}

/**
 * Слова, которыми на странице могло бы обещаться оценивание людей.
 *
 * «Рейтинг» и «карма» запрещены §12 `product-principles-client-centricity`;
 * «баллы», «звёзды», `score`, `rank` — те же обещания другими словами. Список
 * намеренно шире буквы запрета: гард обязан ловить **смысл**, а не конкретную
 * формулировку (P-4 код-ревью 10.4 — узкий регекс пропускал «Мы показываем
 * рейтинг участников: он растёт от встреч и влияет на подбор»).
 */
const RATING_TERM =
  /(рейтинг|балл|карм|звёзд|звезд|оценк|оценива|rating|score|rank)/i;

/**
 * Отрицания, которые снимают утверждение об оценивании.
 *
 * Список закрытый и перечислительный, а не «любое `не`»: «Мы не скрываем, что
 * рейтинг растёт» содержит `не`, но рейтинг всё равно обещает. Поэтому здесь
 * только сказуемые, отрицающие **существование** оценивания или его **работу**
 * («рейтинга нет», «не показываем», «не зависит», «никак»).
 */
const RATING_NEGATED =
  /(нет|не\s+(существу|показыва|став|счита|превраща|использ|оценив|сравнив|влия|завис|явля|даёт|дает|будет|завод|ввод|хран)|отсутству|никак|ни\s+один|ни\s+разу|без\s+(рейтинг|балл|карм|оцен)|не\s+как\s+оценк)/i;

/**
 * Находит в тексте утверждения о рейтинге, баллах или карме.
 *
 * Проверяется не наличие слова, а **утверждение**. «Рейтинга, баллов и кармы в
 * сервисе нет» слово содержит, но обещанием не является. Поэтому текст режется
 * на смысловые отрезки по знакам конца предложения и по противопоставлениям
 * «но / однако / зато» — иначе «Рейтинга нет, но баллы растут» прошло бы целиком
 * как отрицание, — и каждый отрезок проверяется отдельно: есть термин, значит
 * обязано быть отрицание.
 *
 * @param text видимый текст страницы (теги уже вырезаны)
 * @returns отрезки, обещающие оценивание; пустой массив — страница чиста
 */
function ratingClaims(text: string): string[] {
  const clauses = text
    .split(/[.!?\n]+|\s+(?:но|однако|зато)\s+|,\s*(?:но|однако|зато)\s+/i)
    .map((clause) => clause.trim())
    .filter((clause) => clause.length > 0);
  return clauses.filter((clause) => RATING_TERM.test(clause) && !RATING_NEGATED.test(clause));
}

/**
 * Видимый текст страницы: теги вырезаны, концы блоков — как концы фраз.
 *
 * `</li>`, `</p>`, `</h2>`, `</section>` и `<br>` превращаются в точку: без
 * этого пункты списка склеились бы в одну строку, и «нет» из соседнего пункта
 * снимало бы чужое обещание.
 *
 * @param html разметка страницы
 */
function visibleText(html: string): string {
  return html
    .replace(/<[^>]+>/g, (tag) =>
      /^<\/(?:li|p|h[1-6]|section|div|main|article|nav)>$/i.test(tag) || /^<br\b/i.test(tag)
        ? ". "
        : " ",
    )
    .replace(/&[a-z]+;/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Достаёт значения атрибутов `href` в порядке появления.
 * @param html разметка страницы
 */
function hrefs(html: string): string[] {
  return [...html.matchAll(/<a\b[^>]*\bhref="([^"]*)"/g)].map((m) => m[1]);
}

/**
 * Достаёт открывающие теги `<a …>` целиком — для проверки классов.
 * @param html разметка страницы
 */
function anchorTags(html: string): string[] {
  return [...html.matchAll(/<a\b[^>]*>/g)].map((m) => m[0]);
}

/**
 * Порядок заголовков в HTML: `["h1", "h2", "h2", …]`.
 * @param html разметка страницы
 */
function headingOrder(html: string): string[] {
  return [...html.matchAll(/<(h[1-6])\b/g)].map((m) => m[1]);
}

describe("Страница /rules: доступ без авторизации (AC-01)", () => {
  it("рендерится без сессии и без запросов к бэкенду", () => {
    // AC-01.2: redirect() в RSC бросает — до ассертов дело бы не дошло.
    expect(pageHtml().length).toBeGreaterThan(0);
    expect(pageHtml()).toContain("<main");
  });

  it("содержит h1 с названием правил", () => {
    // AC-01.2: страница — не пустая заглушка.
    expect(pageHtml()).toMatch(/<h1[^>]*>Правила модерации<\/h1>/);
  });

  it("в исходнике нет проверки сессии и редиректа", () => {
    // AC-01.1: статический гард. Рендер не поймал бы try/catch вокруг cookies().
    for (const forbidden of ["redirect(", "getSession", "cookies(", "headers(", "middleware"]) {
      expect(PAGE_CODE, `в page.tsx найдено «${forbidden}»`).not.toContain(forbidden);
    }
  });

  it("лежит в группе (public), а не в (app) или (mod)", () => {
    // AC-01.3: защита маршрутов живёт в app/(app)/app/layout.tsx.
    expect(TEST_DIR).toContain(join("app", "(public)", "rules"));
    expect(TEST_DIR).not.toContain(join("app", "(app)"));
    expect(TEST_DIR).not.toContain(join("app", "(mod)"));
  });

  it("объявляет индексацию, в отличие от /privacy и /terms", () => {
    // D-10.4-4: расхождение с соседями осознанное.
    expect(metadata.robots).toEqual({ index: true, follow: true });
    expect(metadata.title).toContain("Правила");
  });
});

describe("Страница /rules: семантика и доступность (AC-02)", () => {
  it("ровно один h1", () => {
    // AC-02.1
    expect(headingOrder(pageHtml()).filter((tag) => tag === "h1")).toHaveLength(1);
  });

  it("заголовки идут без пропуска уровней: h1 → h2, без h3 и ниже", () => {
    // AC-02.1: h3 разрешён только после h2, h4 — после h3.
    const order = headingOrder(pageHtml());
    expect(order[0]).toBe("h1");
    let previous = 1;
    for (const tag of order) {
      const level = Number.parseInt(tag.slice(1), 10);
      expect(level - previous).toBeLessThanOrEqual(1);
      previous = level;
    }
  });

  it("все разделы правил отрисованы как h2 в порядке константы", () => {
    // AC-02.2 + D-10.4-7: структура — обещание, а не оформление.
    const titles = MODERATION_RULES_SECTIONS.map((s) => s.title);
    const rendered = [...pageHtml().matchAll(/<h2[^>]*>(.*?)<\/h2>/g)].map((m) => m[1]);
    expect(rendered).toEqual(titles);
  });

  it("один main и ни одного псевдозаголовка", () => {
    // AC-02.2: `<p class="font-bold">` вместо h2 — типичная имитация заголовка.
    expect([...pageHtml().matchAll(/<main\b/g)]).toHaveLength(1);
    expect(pageHtml()).not.toMatch(/<p[^>]*font-bold/);
    expect(pageHtml()).not.toMatch(/<div[^>]*font-bold/);
  });

  it("каждый раздел — section с id и списком пунктов", () => {
    // AC-02.2: section + ul/li; id нужен для ссылок на раздел.
    for (const section of MODERATION_RULES_SECTIONS) {
      expect(pageHtml()).toMatch(new RegExp(`<section[^>]*id="${section.id}"`));
    }
    expect(pageHtml().match(/<ul\b/g)?.length).toBe(MODERATION_RULES_SECTIONS.length);
  });

  it("тап-зона каждой ссылки не меньше 44 px", () => {
    // AC-02.3: `min-h-11` — приём, уже принятый в проекте (43 вхождения).
    const tags = anchorTags(pageHtml());
    expect(tags.length).toBeGreaterThanOrEqual(3);
    for (const tag of tags) {
      expect(tag, `ссылка без тач-зоны: ${tag}`).toContain("min-h-11");
    }
  });

  it("у каждой ссылки видимый фокус, outline-none не используется", () => {
    // AC-02.4: outline-offset-2 + outline-focus-ring — иначе фокус невидим.
    for (const tag of anchorTags(pageHtml())) {
      expect(tag).toContain("focus-visible:outline");
      expect(tag).toContain("focus-visible:outline-offset-2");
      expect(tag).toContain("focus-visible:outline-focus-ring");
      expect(tag).not.toContain("outline-none");
    }
  });

  it("нет литеральных цветов и произвольных значений", () => {
    // AC-02.5: гейт 1/5 ловит это же в исходнике; тест ловит в разметке.
    expect(PAGE_CODE).not.toMatch(/\b(bg|text|border|outline|ring|fill|stroke)-\[#/);
    expect(PAGE_CODE).not.toMatch(/\b(bg-white|bg-black|text-white|text-black)\b/);
    expect(pageHtml()).not.toMatch(/#[0-9a-fA-F]{3,8}\b/);
  });

  it("нет анимаций: prefers-reduced-motion нечего отключать", () => {
    // AC-02.7
    expect(PAGE_CODE).not.toContain("animate-");
    expect(PAGE_CODE).not.toContain("transition-");
  });

  it("утверждает, что внешность, доход и образование не оцениваются", () => {
    // AC-02.6 + NFR53: тест ищет формулировку, а не «раздел существует».
    expect(pageHtml()).toContain("Внешность");
    expect(pageHtml()).toContain("Доход");
    expect(pageHtml()).toContain("Образование");
    expect(pageHtml()).toMatch(/не оцениваем/i);
  });

  it("не обещает рейтинга и не грозит сроками блокировки", () => {
    // NFR54 + D-10.4-7: запрет на карму и на «бан до решения».
    //
    // Позитивная половина: страница ЯВНО говорит, что рейтинга нет.
    expect(pageHtml()).toMatch(/Рейтинга, баллов и кармы в сервисе нет/i);
    // Негативная половина ищет ОБЕЩАНИЕ, а не слово «рейтинг»: отрицание
    // («рейтинга нет») обязано проходить, иначе тест запрещал бы сам запрет.
    //
    // Проверяется утверждение, а не формулировка (P-4 код-ревью 10.4): прежний
    // регекс ждал «ваш» или глагол сразу после слова «рейтинг» и зеленел на
    // «Мы показываем рейтинг участников: он растёт от встреч и влияет на
    // подбор». Здесь каждый смысловой отрезок текста с термином обязан нести
    // отрицание, иначе он — обещание.
    expect(ratingClaims(visibleText(pageHtml()))).toEqual([]);
    expect(pageHtml()).not.toMatch(/(звёзд|звезд)[а-я]* (за|от) (встреч|активност)/i);
    expect(pageHtml()).not.toMatch(/блокировк[а-я]*[^.]{0,40}до решения/i);
  });
});

describe("Гард NFR54: что считается обещанием рейтинга (P-4)", () => {
  /**
   * Примеры, которые гард ОБЯЗАН поймать. Первый — ровно та формулировка,
   * которой прошёл прежний регекс (P-4 код-ревью 10.4): между «рейтинг» и
   * глаголом стоит «участников», подлежащее — «он».
   */
  const CLAIMS: readonly (readonly [string, string])[] = [
    [
      "мы показываем",
      "Мы показываем рейтинг участников: он растёт от встреч и влияет на подбор.",
    ],
    ["притяжательное", "Ваш рейтинг растёт от встреч."],
    ["падежная форма", "Участники с высоким рейтингом получают больше приглашений."],
    ["баллы", "Баллы начисляются за каждую встречу."],
    ["карма", "Карма растёт, если человек приходит на встречи."],
    ["противопоставление", "Рейтинга нет, но баллы растут."],
    // Класс «оценк/оценива» (P-4 доработка, код-ревью 10.4 r2): §12 запрещает
    // ОЦЕНИВАНИЕ людей, и сама страница формулирует запрет словом «оценку»
    // (`moderation-rules.ts`, раздел «Что мы не оцениваем никогда»). Гард,
    // не знающий этого слова, пропускал обещание, ради запрета которого
    // написан: «оценки влияют на подбор» — это ровно подбор по оценке.
    ["оценки влияют на подбор", "Оценки участников влияют на подбор."],
    ["высокая оценка", "Участники с высокой оценкой получают больше приглашений."],
    ["оценивание людей", "Оценивание людей по фото — основа подбора."],
    ["оцениваем по шкале", "Мы оцениваем участников по пятибалльной шкале."],
    ["оценка в профиле", "Оценка человека видна другим участникам в его профиле."],
  ];

  /** Примеры, которые гард обязан пропустить: отрицание — не обещание. */
  const NEGATIONS: readonly (readonly [string, string])[] = [
    [
      "фраза-запрет страницы",
      "Рейтинга, баллов и кармы в сервисе нет: мы не превращаем людей в числовую оценку друг для друга.",
    ],
    ["не показываем", "Мы не показываем баллы и не считаем карму."],
    ["не влияет", "Рейтинг не влияет на подбор."],
    ["никаких", "Никаких звёзд за встречи мы не ставим."],
    ["нет звёзд", "Оценок в звёздах нет."],
    // Ложное срабатывание на СОБСТВЕННОМ тексте страницы (проверено ревьюером):
    // без `не\s+как\s+оценк` в RATING_NEGATED эта фраза краснела после
    // расширения RATING_TERM классом «оценк». Отрицание сравнительной
    // конструкции — не обещание.
    [
      "не как оценка человека",
      "Возраст нужен только для подтверждения 18+ и подбора по интересам, но не как оценка человека.",
    ],
    [
      "не оцениваем и не сравниваем",
      "Внешность: черты лица, фигуру, рост и вес мы не оцениваем и не сравниваем.",
    ],
  ];

  for (const [name, text] of CLAIMS) {
    it(`ловит обещание: ${name}`, () => {
      // Обещание возвращается отрезком, а не всей фразой: «Рейтинга нет, но баллы
      // растут» даёт ровно половину-обещание, свободную от отрицания.
      const claims = ratingClaims(visibleText(`<p>${text}</p>`));
      expect(claims.length).toBeGreaterThan(0);
      for (const claim of claims) {
        expect(claim).toMatch(RATING_TERM);
        expect(claim).not.toMatch(RATING_NEGATED);
      }
    });
  }

  for (const [name, text] of NEGATIONS) {
    it(`пропускает отрицание: ${name}`, () => {
      expect(ratingClaims(visibleText(`<p>${text}</p>`))).toEqual([]);
    });
  }

  it("снимает отрицание только у своего отрезка, а не у всего текста", () => {
    // «Рейтинга нет, но баллы растут» — половина-отрицание не прикрывает половину-обещание.
    const claims = ratingClaims(visibleText("<p>Рейтинга нет, но баллы растут.</p>"));
    expect(claims).toHaveLength(1);
    expect(claims[0]).toContain("баллы растут");
  });

  it("разные пункты списка не склеиваются в один отрезок", () => {
    // Без разделения по `</li>` «нет» из первого пункта снимало бы второе обещание.
    const html = "<ul><li>Рейтинга нет.</li><li>Карма растёт от встреч.</li></ul>";
    expect(ratingClaims(visibleText(html))).toEqual(["Карма растёт от встреч"]);
  });
});

