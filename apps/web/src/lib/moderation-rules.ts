/**
 * Нормализованный текст правил для SHA-256 (AC-03.3, Task 0.3).
 *
 * Правила нормализации зафиксированы, чтобы хеш не менялся от косметики:
 * каждый заголовок и каждый пункт обрезаются по краям (`trim`), между ними
 * ровно один `\n`, порядок = порядок массива. Версия и дата в хеш НЕ входят:
 * их бамп сам по себе не должен выглядеть как правка текста.
 *
 * Функция живёт рядом с текстом, а не в тесте, — иначе страница и тест
 * считали бы хеш от разных строк и гард ничего бы не проверял.
 */
export function rulesTextForHash(): string {
  const lines: string[] = [];
  for (const section of MODERATION_RULES_SECTIONS) {
    lines.push(section.title.trim());
    for (const item of section.items) {
      lines.push(item.trim());
    }
  }
  return lines.join("\n");
}

/** Названия месяцев в родительном падеже: «26 октября 2026». */
const MONTHS_GENITIVE: readonly string[] = [
  "января",
  "февраля",
  "марта",
  "апреля",
  "мая",
  "июня",
  "июля",
  "августа",
  "сентября",
  "октября",
  "ноября",
  "декабря",
];

/**
 * Форматирует дату редакции по-русски: `2026-10-26` → «26 октября 2026».
 *
 * Своя реализация, а не `Intl.DateTimeFormat`: в jsdom и в серверном рендере
 * локаль по умолчанию различается, и тест на строку версии стал бы зависеть от
 * окружения. Формат здесь фиксирован и не является настройкой пользователя.
 */
export function formatEffectiveFrom(iso: string): string {
  const parts = iso.split("-");
  if (parts.length !== 3) return iso;
  const year = parts[0];
  const month = Number.parseInt(parts[1], 10);
  const day = Number.parseInt(parts[2], 10);
  const monthName = MONTHS_GENITIVE[month - 1];
  if (monthName === undefined || Number.isNaN(day)) return iso;
  return `${day} ${monthName} ${year}`;
}

/** Готовая строка редакции для страницы: «Редакция 1.0 · действует с 26 октября 2026». */
export function rulesVersionLabel(): string {
  return `Редакция ${MODERATION_RULES_VERSION} · действует с ${formatEffectiveFrom(MODERATION_RULES_EFFECTIVE_FROM)}`;
}
