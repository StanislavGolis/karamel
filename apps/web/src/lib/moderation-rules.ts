/**
 * Правила модерации сервиса «Карамель» (стори 10.4; AC-03.1, D-10.4-1…3).
 *
 * **Почему константа в коде, а не в БД.** Правила обязаны открываться ДО
 * регистрации при любом состоянии бэкенда: текст из БД потребовал бы миграцию,
 * API, кэш и страницу ошибки на случай недоступности хранилища. Редактора
 * правил в пилоте нет и не планируется, поэтому база дала бы всю стоимость и
 * ноль пользы (D-10.4-1). Версия текста — это версия в git: `git log` по этому
 * файлу и есть аудит изменений.
 *
 * **Почему версия и дата — отдельные константы.** AC-03.1 требует, чтобы версия
 * была объявлена ровно в одном месте: страница читает `MODERATION_RULES_VERSION`
 * и не дублирует строку «1.0» у себя. Иначе при бампе версии один из двух
 * литералов забывается, и документ начинает врать о своей редакции.
 *
 * **Гард.** `rulesTextForHash()` нормализует текст, а тест сверяет его SHA-256
 * с ожидаемым. Изменил формулировку, но не бампнул версию и хеш — тест красный
 * (`__tests__/moderation-rules-version.test.ts`). Это единственный способ
 * сделать «версия фиксируется» проверяемым, а не комментарием (D-10.4-3).
 *
 * **Чего в тексте быть не должно** (D-10.4-7): карательного тона, сроков
 * блокировки «до решения», рейтингов и кармы (NFR54), обещаний автоматической
 * модерации — её нет, решения принимает человек.
 */

