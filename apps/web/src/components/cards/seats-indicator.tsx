/**
 * Свободные места (UX §848, `SeatsIndicator`; стори 4.5, Task 7.2; AC-09).
 *
 * Три правила UX, каждое — про доверие, а не про вёрстку:
 *
 * 1. **Склонение обязательно**: «1 место», «2 места», «5 мест». Форма
 *    «1 мест» читается как автоматический перевод и обесценивает весь экран;
 * 2. **При нуле компонент невидим** — вместо него статус `full` («Компания
 *    собрана»). «Свободно 0 мест» звучит как приглашение, которого нет;
 * 3. **Никаких счётчиков спроса**: ни «просмотрели», ни «заявок 3». UX §147:
 *    спокойствие («меня не оценивают») — продуктовое свойство, и счётчики
 *    спроса его разрушают.
 *
 * `aria-live` здесь НЕТ: у зрителя объявлений быть не должно (UX §848).
 * Живой регион — только у автора при изменении состава, и это 5б.
 */

/**
 * Русское склонение по числу: 1 → «место», 2–4 → «места», иначе «мест».
 *
 * Исключение — 11–14: они дают «мест», хотя оканчиваются на 1–4
 * («11 мест», не «11 места»). Без этой ветки индикатор врал бы как раз
 * на числах, которые чаще всего встречаются (компания 2–6 человек, но
 * `filled_count` приходит и как 11+ на карточках закрытых встреч).
 */
export function pluralizeSeats(count: number): string {
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 14) return "мест";
  if (mod10 === 1) return "место";
  if (mod10 >= 2 && mod10 <= 4) return "места";
  return "мест";
}

type SeatsIndicatorProps = {
  /** Вместимость карточки (1–6). */
  capacity: number;
  /** Занятые места. */
  filledCount: number;
};

export function SeatsIndicator({ capacity, filledCount }: SeatsIndicatorProps) {
  const free = capacity - filledCount;
  // AC-09, UX §848: при нуле статус показывает `EventCard` («Компания
  // собрана»), а не этот компонент — иначе пустота звучала бы приглашением.
  if (free <= 0) return null;

  return (
    <span className="text-sm font-medium text-ink-secondary">
      Свободно {free} {pluralizeSeats(free)}
    </span>
  );
}
