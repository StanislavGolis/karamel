/**
 * Индикатор состояния WS-соединения (стори 6.5, Task 7.2; AC-03, NFR57).
 *
 * **Почему тонкая полоса, а не модалка.** Модалка перекрывает переписку и
 * требует действия — то есть наказывает пользователя за чужую проблему
 * (плохую сеть). Полоса информирует, не мешая читать уже загруженное.
 *
 * **Почему при `online` не рисуется вообще.** Успешное соединение — норма,
 * а не событие: постоянно видимая плашка «всё хорошо» превращается в шум,
 * который перестают замечать, и настоящая проблема остаётся незамеченной.
 *
 * **Почему текст, а не только цвет** (NFR57): цвет — единственный носитель
 * смысла недоступен при дальтонизме и в монохромном режиме. Текст
 * `«Нет связи — переподключаемся»` читается скринридером и остаётся понятным
 * без стилей.
 */

import type { ConnectionState } from "@/lib/ws-client";

type ConnectionIndicatorProps = {
  state: ConnectionState;
};

/**
 * Полоса состояния: `2–3px` высотой, всегда над перепиской.
 *
 * При `online` возвращает `null`: см. докстринг модуля. При `offline`
 * показывается ВТОРОЕ значение признака — «связи нет» отличается от
 * «переподключаемся»: первое означает, что попытки прекращены, второе —
 * что клиент уже работает над этим.
 */
export function ConnectionIndicator({ state }: ConnectionIndicatorProps) {
  if (state === "online") return null;

  const text =
    state === "offline" ? "Нет связи" : "Нет связи — переподключаемся";

  return (
    <div
      // `role="status"` + `aria-live="polite"`: скринридер сообщит об
      // изменении, но не перебьёт текущее чтение (в отличие от `alert`).
      role="status"
      aria-live="polite"
      data-connection-state={state}
      className="flex h-[3px] w-full items-center overflow-hidden rounded-sm bg-surface"
    >
      {/* Текст визуально скрыт, но доступен скринридеру и тесту: полоса
          высотой 3px не вмещает строку, а `aria-label` на пустом элементе
          читается не всеми скринридерами. */}
      <span className="sr-only">{text}</span>
      <span
        aria-hidden="true"
        className={`h-[3px] w-1/3 rounded-sm ${
          state === "offline" ? "bg-danger" : "bg-warning"
        }`}
      />
    </div>
  );
}
